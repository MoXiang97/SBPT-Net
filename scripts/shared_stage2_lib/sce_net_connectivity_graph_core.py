def dense_sample_closed_contour_3d_np(control_xyz: np.ndarray, samples_per_segment: int = 16) -> np.ndarray:
    """Dense sample a closed 3D polyline for CloudCompare visualization."""
    control_xyz = np.asarray(control_xyz, dtype=np.float32)
    k = len(control_xyz)
    if k == 0:
        return np.zeros((0, 3), dtype=np.float32)
    nxt = np.roll(control_xyz, shift=-1, axis=0)
    t = (np.arange(max(1, int(samples_per_segment)), dtype=np.float32) / max(1, int(samples_per_segment))).reshape(1, -1, 1)
    pts = control_xyz[:, None, :] * (1.0 - t) + nxt[:, None, :] * t
    return pts.reshape(-1, 3).astype(np.float32)


