def _v19_deep_cache_record_path(cfg: Config, record: Dict[str, object]) -> str:
    """Per-file cache path for frozen upstream outputs used by V19 search.

    This cache stores only model outputs / coordinates that are already computed
    before deterministic V19 extraction. It does not store final contour/search
    results and does not change any model, seed, or search behavior.
    """
    root = str(getattr(cfg, "v19_deep_cache_root", os.path.join(BASE_DIR, "outputs", "V19_DeepOutputCache_r6_K64_PTCluster")))
    subset = str(record.get("subset", "unknown"))
    sid = str(record.get("sample_id", sample_id(record.get("path", "unknown"))))
    d = os.path.join(root, subset)
    ensure_dir(d)
    return os.path.join(d, sid + "_v19deep.npz")


def _save_v19_deep_cache(records: List[Dict[str, object]], cfg: Config, thresholds: Optional[Dict[str, object]] = None) -> pd.DataFrame:
    """Save frozen V19 upstream outputs for later path-search-only debugging.

    Saved arrays are the outputs of the already completed deep-learning stages:
      prob, token_transformer_prob, cluster_refiner_prob, pt_evidence_prob,
      xyz3d_norm, pt_hidden, base_spacing, xyz_center3.
    Label/downsampled data are intentionally not duplicated because they are
    already loaded from the downsample cache in every run.
    """
    root = str(getattr(cfg, "v19_deep_cache_root", os.path.join(BASE_DIR, "outputs", "V19_DeepOutputCache_r6_K64_PTCluster")))
    ensure_dir(root)
    rows = []
    for r in tqdm(records, desc="Save V19 deep-output cache"):
        ds = r.get("downsampled", {})
        n = int(len(ds.get("label", [])))
        path = _v19_deep_cache_record_path(cfg, r)
        sid = str(r.get("sample_id", sample_id(r.get("path", "unknown"))))
        arrays = {
            "prob": np.asarray(r.get("prob", np.zeros(n, dtype=np.float32)), dtype=np.float32),
            "token_transformer_prob": np.asarray(r.get("token_transformer_prob", np.zeros(n, dtype=np.float32)), dtype=np.float32),
            "cluster_refiner_prob": np.asarray(r.get("cluster_refiner_prob", np.zeros(n, dtype=np.float32)), dtype=np.float32),
            "pt_evidence_prob": np.asarray(r.get("pt_evidence_prob", np.zeros(n, dtype=np.float32)), dtype=np.float32),
            "xyz3d_norm": np.asarray(r.get("xyz3d_norm", np.zeros((n, 3), dtype=np.float32)), dtype=np.float32),
            "pt_hidden": np.asarray(r.get("pt_hidden", np.zeros((n, int(getattr(cfg, "token_transformer_hidden_dim", 96))), dtype=np.float16)), dtype=np.float16),
            "base_spacing": np.asarray(float(r.get("base_spacing", estimate_base_spacing_from_ds_v14(ds) if n > 0 else 1.0)), dtype=np.float32),
            "xyz_center3": np.asarray(r.get("xyz_center3", np.zeros(3, dtype=np.float32)), dtype=np.float32),
            "n_tokens": np.asarray(n, dtype=np.int64),
        }
        np.savez_compressed(path, **arrays)
        rows.append({
            "domain": r.get("domain", ""),
            "split": r.get("split", ""),
            "subset": r.get("subset", ""),
            "sample_id": sid,
            "n_tokens": n,
            "cache_path": path,
            "saved": True,
        })
    manifest = pd.DataFrame(rows)
    if not manifest.empty:
        manifest.to_csv(os.path.join(root, "manifest.csv"), index=False)
    if thresholds is not None:
        with open(os.path.join(root, "thresholds.json"), "w", encoding="utf-8") as f:
            json.dump(thresholds, f, ensure_ascii=False, indent=2)
    return manifest


def _load_v19_deep_cache_into_records(records: List[Dict[str, object]], cfg: Config) -> Dict[str, object]:
    """Load frozen V19 upstream outputs and attach them to records.

    This is used by --only_run_v19_from_cache to skip raw MLP / Token Transformer /
    cluster-aware PT training and inference. It does not load final V19 contour
    outputs; those are recomputed after loading.
    """
    root = str(getattr(cfg, "v19_deep_cache_root", os.path.join(BASE_DIR, "outputs", "V19_DeepOutputCache_r6_K64_PTCluster")))
    skip_missing = bool(getattr(cfg, "v19_deep_cache_skip_missing", False))
    rows = []
    kept_records: List[Dict[str, object]] = []
    for r in tqdm(records, desc="Load V19 deep-output cache"):
        ds = r.get("downsampled", {})
        n = int(len(ds.get("label", [])))
        path = _v19_deep_cache_record_path(cfg, r)
        sid = str(r.get("sample_id", sample_id(r.get("path", "unknown"))))
        if not os.path.exists(path):
            rows.append({
                "domain": r.get("domain", ""), "split": r.get("split", ""), "subset": r.get("subset", ""),
                "sample_id": sid, "n_tokens": n, "cache_path": path, "loaded": False, "reason": "missing_cache",
            })
            if skip_missing:
                continue
            raise FileNotFoundError(
                f"[V19DeepCache] ERROR: Current is cache-only mode (only_run_v19_from_cache=True), "
                f"but V19 deep-output cache missing for {sid}: {path}\n"
                f"Please run --full_run_deep_learning to regenerate the deep cache."
            )
        data = np.load(path, allow_pickle=True)
        cached_n = int(np.asarray(data.get("n_tokens", n)).reshape(-1)[0]) if "n_tokens" in data.files else n
        if cached_n != n:
            msg = f"token_count_mismatch cache={cached_n} current={n}"
            rows.append({
                "domain": r.get("domain", ""), "split": r.get("split", ""), "subset": r.get("subset", ""),
                "sample_id": sid, "n_tokens": n, "cache_path": path, "loaded": False, "reason": msg,
            })
            if skip_missing:
                continue
            raise ValueError(f"V19 cache token count mismatch for {sid}: {msg}")
        for key in ["prob", "token_transformer_prob", "cluster_refiner_prob", "pt_evidence_prob"]:
            if key in data.files:
                arr = np.asarray(data[key], dtype=np.float32)
            else:
                arr = np.zeros(n, dtype=np.float32)
            if len(arr) != n:
                raise ValueError(f"V19 cache array {key} length mismatch for {sid}: {len(arr)} vs {n}")
            r[key] = arr
        if "xyz3d_norm" in data.files:
            xyz3d_norm = np.asarray(data["xyz3d_norm"], dtype=np.float32)
        else:
            xyz = np.asarray(ds.get("xyz", np.zeros((n, 3), dtype=np.float32)), dtype=np.float32)
            bs = estimate_base_spacing_from_ds_v14(ds) if n > 0 else 1.0
            xyz3d_norm, center3 = robust_center_normalize_3d_v15(xyz, bs)
            r["xyz_center3"] = center3.astype(np.float32)
            r["base_spacing"] = float(bs)
        if xyz3d_norm.shape != (n, 3):
            raise ValueError(f"V19 cache xyz3d_norm shape mismatch for {sid}: {xyz3d_norm.shape} vs {(n, 3)}")
        r["xyz3d_norm"] = xyz3d_norm.astype(np.float32)
        if "pt_hidden" in data.files:
            r["pt_hidden"] = np.asarray(data["pt_hidden"], dtype=np.float16)
        else:
            r["pt_hidden"] = np.zeros((n, int(getattr(cfg, "token_transformer_hidden_dim", 96))), dtype=np.float16)
        if "base_spacing" in data.files:
            r["base_spacing"] = float(np.asarray(data["base_spacing"]).reshape(-1)[0])
        elif "base_spacing" not in r:
            r["base_spacing"] = float(estimate_base_spacing_from_ds_v14(ds) if n > 0 else 1.0)
        if "xyz_center3" in data.files:
            r["xyz_center3"] = np.asarray(data["xyz_center3"], dtype=np.float32).reshape(3)
        elif "xyz_center3" not in r:
            r["xyz_center3"] = np.zeros(3, dtype=np.float32)
        rows.append({
            "domain": r.get("domain", ""), "split": r.get("split", ""), "subset": r.get("subset", ""),
            "sample_id": sid, "n_tokens": n, "cache_path": path, "loaded": True, "reason": "ok",
        })
        kept_records.append(r)

    if skip_missing and len(kept_records) != len(records):
        records[:] = kept_records

    thresholds = {}
    th_path = os.path.join(root, "thresholds.json")
    if os.path.exists(th_path):
        with open(th_path, "r", encoding="utf-8") as f:
            thresholds = json.load(f)
    else:
        print(f"[V19DeepCache] WARNING: thresholds.json not found under {root}; using default thresholds where needed.")
    return {"thresholds": thresholds, "load_rows": pd.DataFrame(rows)}

