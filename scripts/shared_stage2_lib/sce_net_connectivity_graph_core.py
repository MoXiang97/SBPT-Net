class _V19UnionFind:
    def __init__(self, n: int):
        self.parent = list(range(int(n)))
        self.size = [1] * int(n)
    def find(self, x: int) -> int:
        p = self.parent[x]
        if p != x:
            self.parent[x] = self.find(p)
        return self.parent[x]
    def union(self, a: int, b: int) -> None:
        ra, rb = self.find(int(a)), self.find(int(b))
        if ra == rb:
            return
        if self.size[ra] < self.size[rb]:
            ra, rb = rb, ra
        self.parent[rb] = ra
        self.size[ra] += self.size[rb]


def _v19_component_metrics(pts: np.ndarray, probs: np.ndarray, high_thr: float) -> Dict[str, float]:
    pts = np.asarray(pts, dtype=np.float32)
    probs = np.asarray(probs, dtype=np.float32)
    n = int(len(pts))
    if n == 0:
        return dict(points=0, high_points=0, mean_prob=0.0, high_mean_prob=0.0, length=0.0, width=0.0, linearness=0.0, score=-1e9)
    high = probs >= float(high_thr)
    st = pca_fragment_stats(pts.astype(np.float32)) if n >= 2 else {"length": 0.0, "width": 0.0, "linearness": 0.0}
    length = float(st.get("length", 0.0))
    width = float(st.get("width", 0.0))
    linearness = float(st.get("linearness", 0.0))
    mean_prob = float(np.mean(probs)) if n else 0.0
    high_mean = float(np.mean(probs[high])) if np.any(high) else mean_prob
    # Engineering target: many high-confidence points, spatially grouped, thin/line-like.
    # Single high-score isolated points get very low scores because high_points and length are small.
    high_count = int(np.sum(high))
    slender = length / (width + 1e-3)
    density_bonus = math.log1p(float(n))
    score = (2.0 * high_count + 0.15 * n) * (0.25 + high_mean) * (0.5 + linearness) * (1.0 + 0.15 * min(slender, 20.0)) * (1.0 + 0.05 * density_bonus)
    return dict(points=n, high_points=high_count, mean_prob=mean_prob, high_mean_prob=high_mean, length=length, width=width, linearness=linearness, score=float(score))


def _v19_build_components(xyz_norm: np.ndarray, probs: np.ndarray, weak_thr: float, max_step_norm: float, fallback_topk: int) -> Tuple[List[np.ndarray], np.ndarray]:
    n = int(len(xyz_norm))
    if n == 0:
        return [], np.zeros(0, dtype=np.int64)
    weak_idx = np.where(np.asarray(probs) >= float(weak_thr))[0].astype(np.int64)
    if len(weak_idx) < max(8, int(fallback_topk)):
        order = np.argsort(-np.asarray(probs))[:min(n, max(8, int(fallback_topk)))]
        weak_idx = np.unique(np.concatenate([weak_idx, order.astype(np.int64)])).astype(np.int64)
    if len(weak_idx) == 0:
        return [], weak_idx
    pts = xyz_norm[weak_idx]
    uf = _V19UnionFind(len(weak_idx))
    tree = cKDTree(pts)
    pairs = tree.query_pairs(r=float(max_step_norm))
    for a, b in pairs:
        uf.union(int(a), int(b))
    buckets: Dict[int, List[int]] = {}
    for local_i in range(len(weak_idx)):
        root = uf.find(local_i)
        buckets.setdefault(root, []).append(local_i)
    comps = [weak_idx[np.asarray(v, dtype=np.int64)] for v in buckets.values()]
    comps.sort(key=lambda arr: len(arr), reverse=True)
    return comps, weak_idx


def _v19_seed_purity_proxy_score(
    comp: np.ndarray,
    xyz_norm: np.ndarray,
    probs: np.ndarray,
    base_spacing: float,
    cfg: Config,
) -> Dict[str, float]:
    """GT-free precision-first score for reranking only the old Top-K seed candidates.

    The score intentionally does NOT use Label/GT.  It measures whether a component
    is internally high-confidence, stable, and geometrically narrow.  Size is not a
    hard threshold here because the candidate pool is already restricted to the old
    size-first Top1/Top2/Top3 components; at most it can be used as a very small
    tie-breaker.
    """
    comp = np.asarray(comp, dtype=np.int64).reshape(-1)
    if len(comp) == 0:
        return {
            "purity_proxy_score": -1e9,
            "purity_q25_prob": 0.0,
            "purity_q50_prob": 0.0,
            "purity_q75_prob": 0.0,
            "purity_mean_prob": 0.0,
            "purity_prob_std": 0.0,
            "purity_width_mm": 0.0,
            "purity_width_penalty": 0.0,
            "purity_size_tiebreak": 0.0,
        }

    p = np.asarray(probs[comp], dtype=np.float32)
    pts = np.asarray(xyz_norm[comp], dtype=np.float32)
    mean_prob = float(np.mean(p))
    q25 = float(np.quantile(p, 0.25))
    q50 = float(np.quantile(p, 0.50))
    q75 = float(np.quantile(p, 0.75))
    pstd = float(np.std(p))

    width_norm = 0.0
    if len(pts) >= 3:
        st = pca_fragment_stats(pts)
        width_norm = float(st.get("width", 0.0))
    width_mm = float(width_norm * max(float(base_spacing), 1e-6))
    width_ref_mm = max(float(getattr(cfg, "v19_seed_purity_width_ref_mm", 4.0)), 1e-6)
    width_penalty = min(width_mm / width_ref_mm, 3.0)

    # Only a weak tie-breaker: old Top1/Top2/Top3 already provide minimum size.
    size_ref = max(float(getattr(cfg, "v19_seed_purity_size_ref", 64.0)), 1.0)
    size_tiebreak = min(math.log1p(float(len(comp))) / math.log1p(size_ref), 1.0)

    w_q25 = float(getattr(cfg, "v19_seed_purity_w_q25", 0.50))
    w_mean = float(getattr(cfg, "v19_seed_purity_w_mean", 0.30))
    w_q50 = float(getattr(cfg, "v19_seed_purity_w_q50", 0.20))
    w_std = float(getattr(cfg, "v19_seed_purity_w_std", 0.10))
    w_width = float(getattr(cfg, "v19_seed_purity_w_width", 0.08))
    w_size = float(getattr(cfg, "v19_seed_purity_w_size", 0.00))

    score = (
        w_q25 * q25
        + w_mean * mean_prob
        + w_q50 * q50
        - w_std * pstd
        - w_width * width_penalty
        + w_size * size_tiebreak
    )

    return {
        "purity_proxy_score": float(score),
        "purity_q25_prob": float(q25),
        "purity_q50_prob": float(q50),
        "purity_q75_prob": float(q75),
        "purity_mean_prob": float(mean_prob),
        "purity_prob_std": float(pstd),
        "purity_width_mm": float(width_mm),
        "purity_width_penalty": float(width_penalty),
        "purity_size_tiebreak": float(size_tiebreak),
    }


def _v19_select_main_component(
    xyz_norm: np.ndarray,
    probs: np.ndarray,
    comps: List[np.ndarray],
    cfg: Config,
    base_spacing: float = 1.0,
) -> Tuple[np.ndarray, Dict[str, float], List[Dict[str, float]], List[np.ndarray], List[Dict[str, float]]]:
    """Select the final seed component.

    Step 1 keeps the original size-first/effective-score ranking and returns those
    old Top1/Top2/Top3 candidates for diagnostics.
    Step 2 optionally reranks ONLY the old Top-K candidates with a GT-free
    precision-first proxy score and makes that best candidate the new selected seed.

    This implements the current diagnostic hypothesis: do not let arbitrary tiny
    fragments compete, but allow old Top2/Top3 to replace old Top1 when they are
    purer, narrower, and more stable.
    """
    high_thr = float(getattr(cfg, "v19_high_threshold", 0.70))
    min_comp = int(getattr(cfg, "v19_min_component_points", 12))
    min_high = int(getattr(cfg, "v19_min_high_points", 6))
    topk = max(1, int(max(getattr(cfg, "contour_vis_seed_topk", 3), getattr(cfg, "seed_retrieval_topk", 3))))

    rows: List[Dict[str, float]] = []
    scored: List[Tuple[float, int, np.ndarray, Dict[str, float]]] = []

    for ci, comp in enumerate(comps):
        comp = np.asarray(comp, dtype=np.int64)
        m = _v19_component_metrics(xyz_norm[comp], probs[comp], high_thr)
        m["component_id"] = int(ci)

        # Original eligibility logic.  This still defines the old candidate ranking.
        eligible = (m["points"] >= min_comp and m["high_points"] >= min_high)
        effective_score = float(m["score"] if eligible else m["score"] * 0.05)
        m["eligible"] = int(bool(eligible))
        m["effective_score"] = float(effective_score)
        rows.append(m)
        scored.append((effective_score, int(ci), comp.astype(np.int64), dict(m)))

    if not scored:
        return np.zeros(0, dtype=np.int64), {}, rows, [], []

    # Old ranking: size/effective-score first.  The returned top_seed_components keep
    # this OLD order so Top1/Top2/Top3 diagnostics remain comparable to previous runs.
    scored.sort(key=lambda x: (x[0], x[3].get("points", 0), x[3].get("high_points", 0)), reverse=True)

    top_seed_components: List[np.ndarray] = []
    top_seed_rows: List[Dict[str, float]] = []
    for rank, (eff, ci, comp, row) in enumerate(scored[:topk], start=1):
        rr = dict(row)
        rr["seed_rank"] = int(rank)  # old rank
        rr["old_seed_rank"] = int(rank)
        rr.update(_v19_seed_purity_proxy_score(comp, xyz_norm, probs, base_spacing, cfg))
        top_seed_components.append(np.asarray(comp, dtype=np.int64))
        top_seed_rows.append(rr)

    # Default new behavior: rerank only the old Top1/Top2/Top3 by the purity proxy.
    rerank_mode = str(getattr(cfg, "v19_seed_rerank_mode", "top3_purity_first")).lower()
    rerank_topk = min(max(1, int(getattr(cfg, "v19_seed_rerank_topk", 3))), len(top_seed_components))

    selected_pos = 0
    top2_margin_override_used = False
    if rerank_mode in ["top3_purity_first", "purity_first", "topk_purity_first", "top3_purity_first_with_old_top2_prior"] and rerank_topk > 0:
        top2_prior_mode = (rerank_mode == "top3_purity_first_with_old_top2_prior")
        bonus2 = float(getattr(cfg, "v19_seed_old_top2_bonus", 0.06)) if top2_prior_mode else 0.0
        penalty3 = float(getattr(cfg, "v19_seed_old_top3_penalty", 0.06)) if top2_prior_mode else 0.0
        for pos in range(rerank_topk):
            rr = top_seed_rows[pos]
            old_rank = int(rr.get("old_seed_rank", pos + 1))
            rank_prior = 0.0
            if old_rank == 2:
                rank_prior = bonus2
            elif old_rank == 3:
                rank_prior = -penalty3
            raw_score = float(rr.get("purity_proxy_score", -1e9))
            rr["purity_raw_score"] = raw_score
            rr["purity_rank_prior"] = float(rank_prior)
            rr["purity_proxy_score"] = float(raw_score + rank_prior)

        if (
            top2_prior_mode
            and bool(getattr(cfg, "v19_seed_use_top2_margin_override", True))
            and rerank_topk >= 2
        ):
            top2_pos = 1
            top2_raw = float(top_seed_rows[top2_pos].get("purity_raw_score", top_seed_rows[top2_pos].get("purity_proxy_score", -1e9)))
            other_raw_max = -1e9
            for pos in range(rerank_topk):
                if pos == top2_pos:
                    continue
                other_raw_max = max(other_raw_max, float(top_seed_rows[pos].get("purity_raw_score", top_seed_rows[pos].get("purity_proxy_score", -1e9))))
            margin = float(getattr(cfg, "v19_seed_top2_margin", 0.03))
            if top2_raw >= other_raw_max - margin:
                selected_pos = top2_pos
                top2_margin_override_used = True
            else:
                candidates = []
                for pos in range(rerank_topk):
                    rr = top_seed_rows[pos]
                    candidates.append((
                        float(rr.get("purity_proxy_score", -1e9)),
                        float(rr.get("purity_q25_prob", 0.0)),
                        float(rr.get("purity_mean_prob", 0.0)),
                        float(rr.get("effective_score", 0.0)),
                        -int(rr.get("old_seed_rank", pos + 1)),
                        pos,
                    ))
                candidates.sort(reverse=True)
                selected_pos = int(candidates[0][-1])
        else:
            candidates = []
            for pos in range(rerank_topk):
                rr = top_seed_rows[pos]
                # Primary: purity proxy.  Ties: higher q25/mean probability, then old effective score.
                candidates.append((
                    float(rr.get("purity_proxy_score", -1e9)),
                    float(rr.get("purity_q25_prob", 0.0)),
                    float(rr.get("purity_mean_prob", 0.0)),
                    float(rr.get("effective_score", 0.0)),
                    -int(rr.get("old_seed_rank", pos + 1)),
                    pos,
                ))
            candidates.sort(reverse=True)
            selected_pos = int(candidates[0][-1])

    selected = np.asarray(top_seed_components[selected_pos], dtype=np.int64)
    best_metrics = dict(top_seed_rows[selected_pos])
    best_metrics["selection_rank_mode"] = str(rerank_mode)
    best_metrics["selected_from_old_seed_rank"] = int(best_metrics.get("old_seed_rank", selected_pos + 1))
    best_metrics["selected_by_purity_rerank"] = int(selected_pos != 0)
    best_metrics["rerank_candidate_count"] = int(rerank_topk)
    best_metrics["top2_margin_override_used"] = int(bool(top2_margin_override_used))
    best_metrics["purity_raw_score"] = float(best_metrics.get("purity_raw_score", best_metrics.get("purity_proxy_score", np.nan)))
    best_metrics["purity_rank_prior"] = float(best_metrics.get("purity_rank_prior", 0.0))

    # Mark old Top1/Top2/Top3 rows with their new purity order for easier CSV analysis.
    purity_order = sorted(
        range(len(top_seed_rows)),
        key=lambda pos: (
            float(top_seed_rows[pos].get("purity_proxy_score", -1e9)),
            float(top_seed_rows[pos].get("purity_q25_prob", 0.0)),
            float(top_seed_rows[pos].get("purity_mean_prob", 0.0)),
            -int(top_seed_rows[pos].get("old_seed_rank", pos + 1)),
        ),
        reverse=True,
    )
    for new_rank, pos in enumerate(purity_order, start=1):
        top_seed_rows[pos]["purity_new_rank"] = int(new_rank)
        top_seed_rows[pos]["is_new_selected_seed"] = int(pos == selected_pos)
        top_seed_rows[pos]["selection_rank_mode"] = str(rerank_mode)

    return selected.astype(np.int64), best_metrics, rows, top_seed_components, top_seed_rows


def _v19_order_connected_component(xyz_norm: np.ndarray, selected_idx: np.ndarray, probs: np.ndarray, max_step_norm: float) -> Tuple[np.ndarray, Dict[str, float]]:
    """Greedy local ordering with hard max-step. It never creates an edge longer than max_step_norm.
    The output is primarily for visualization/trajectory anchors; the mask uses the selected point set as a corridor support.
    """
    selected_idx = np.asarray(selected_idx, dtype=np.int64)
    if len(selected_idx) <= 1:
        return selected_idx, {"max_edge_norm": 0.0, "illegal_edges": 0, "num_segments": int(len(selected_idx) > 0), "max_gap_norm": 0.0}
    pts = xyz_norm[selected_idx]
    tree = cKDTree(pts)
    unused = set(range(len(selected_idx)))
    # Start from a strong and reasonably central point.
    start = int(np.argmax(probs[selected_idx]))
    ordered_local: List[int] = []
    segments = 0
    illegal_edges = 0
    max_edge = 0.0
    max_gap = 0.0
    current = start
    while unused:
        if current not in unused:
            current = next(iter(unused))
        segments += 1
        ordered_local.append(current)
        unused.remove(current)
        while unused:
            nbrs = tree.query_ball_point(pts[current], r=float(max_step_norm))
            cand = [j for j in nbrs if j in unused]
            if not cand:
                # Start a new visual segment at the strongest remaining point. No edge is created across this gap.
                rem = np.asarray(list(unused), dtype=np.int64)
                if len(rem):
                    d_to_current = np.linalg.norm(pts[rem] - pts[current][None, :], axis=1)
                    max_gap = max(max_gap, float(np.min(d_to_current)))
                    current = int(rem[np.argmax(probs[selected_idx[rem]])])
                break
            # Prefer local, high-confidence continuation. Distance is a hard filter, not a soft global attraction.
            cand_arr = np.asarray(cand, dtype=np.int64)
            d = np.linalg.norm(pts[cand_arr] - pts[current][None, :], axis=1)
            score = probs[selected_idx[cand_arr]] - 0.15 * d / max(float(max_step_norm), 1e-6)
            nxt = int(cand_arr[int(np.argmax(score))])
            edge = float(np.linalg.norm(pts[nxt] - pts[current]))
            if edge > float(max_step_norm) + 1e-6:
                illegal_edges += 1
            max_edge = max(max_edge, edge)
            current = nxt
            ordered_local.append(current)
            unused.remove(current)
    ordered_idx = selected_idx[np.asarray(ordered_local, dtype=np.int64)]
    return ordered_idx, {"max_edge_norm": float(max_edge), "illegal_edges": int(illegal_edges), "num_segments": int(segments), "max_gap_norm": float(max_gap)}



def _v196_parse_float_list(text: object, default: Sequence[float]) -> List[float]:
    if text is None:
        return [float(x) for x in default]
    if isinstance(text, (list, tuple)):
        vals = [float(x) for x in text]
    else:
        vals = []
        for part in str(text).replace(";", ",").split(","):
            part = part.strip()
            if not part:
                continue
            try:
                vals.append(float(part))
            except Exception:
                pass
    vals = [v for v in vals if np.isfinite(v) and v > 0]
    return vals if vals else [float(x) for x in default]


def _v196_polar_frame(xyz_norm: np.ndarray, probs: Optional[np.ndarray] = None, center_mode: str = "existing") -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return center/u/v for a file-local polar frame.

    The frame is only an ordering helper. It never creates final geometry.
    """
    pts = np.asarray(xyz_norm, dtype=np.float32)
    if len(pts) == 0:
        return np.zeros(3, dtype=np.float32), np.array([1, 0, 0], dtype=np.float32), np.array([0, 1, 0], dtype=np.float32)
    center_mode = str(center_mode or "existing")
    if center_mode == "all_downsampled":
        center = np.median(pts, axis=0)
    elif probs is not None and len(probs) == len(pts):
        p = np.asarray(probs, dtype=np.float32)
        # A soft center keeps the polar origin closer to the high-evidence boundary but remains GT-free.
        w = np.clip(p, 0.05, 1.0)
        center = (pts * w[:, None]).sum(axis=0) / max(float(w.sum()), 1e-6)
    else:
        center = np.median(pts, axis=0)
    x = pts - center[None, :]
    if len(pts) >= 3:
        cov = np.cov(x.T)
        vals, vecs = np.linalg.eigh(cov)
        order = np.argsort(vals)[::-1]
        u = vecs[:, order[0]].astype(np.float32)
        v = vecs[:, order[1]].astype(np.float32)
    else:
        u = np.array([1, 0, 0], dtype=np.float32)
        v = np.array([0, 1, 0], dtype=np.float32)
    u = u / (np.linalg.norm(u) + 1e-8)
    v = v - u * float(np.dot(u, v))
    v = v / (np.linalg.norm(v) + 1e-8)
    return center.astype(np.float32), u.astype(np.float32), v.astype(np.float32)


def _v196_polar_theta(xyz_norm: np.ndarray, center: np.ndarray, u: np.ndarray, v: np.ndarray) -> np.ndarray:
    rel = np.asarray(xyz_norm, dtype=np.float32) - np.asarray(center, dtype=np.float32)[None, :]
    a = rel @ np.asarray(u, dtype=np.float32)
    b = rel @ np.asarray(v, dtype=np.float32)
    theta = np.arctan2(b, a)
    theta = np.where(theta < 0, theta + 2.0 * np.pi, theta)
    return theta.astype(np.float32)


def _v196_forward_sector_distance(a: int, b: int, s: int) -> int:
    return int((int(b) - int(a)) % max(int(s), 1))


def _v196_order_seed_by_theta(seed_idx: np.ndarray, theta: np.ndarray) -> np.ndarray:
    seed_idx = np.asarray(seed_idx, dtype=np.int64).reshape(-1)
    if len(seed_idx) <= 1:
        return seed_idx
    th = np.asarray(theta[seed_idx], dtype=np.float32)
    ref = float(np.arctan2(np.mean(np.sin(th)), np.mean(np.cos(th))))
    if ref < 0:
        ref += 2.0 * np.pi
    # Map seed angles to a local interval centered around the circular mean.
    d = (th - ref + np.pi) % (2.0 * np.pi) - np.pi
    unwrapped = ref + d
    order = np.argsort(unwrapped, kind="mergesort")
    return seed_idx[order].astype(np.int64)


def _v196_reduce_seed_chain_shortest(
    seed_idx: np.ndarray,
    xyz_norm: np.ndarray,
    probs: np.ndarray,
    sector_id: np.ndarray,
    sectors: int,
    base_spacing: float,
    cfg: Config,
) -> np.ndarray:
    """Reduce seed chain to one token per sector using a short-path DP."""
    seed_idx = np.asarray(seed_idx, dtype=np.int64).reshape(-1)
    if len(seed_idx) <= 2 or not bool(getattr(cfg, "v196_reduce_seed_one_per_sector", True)):
        return seed_idx
    bs = max(float(base_spacing), 1e-6)
    max_per_sector = max(1, int(getattr(cfg, "v196_seed_candidates_per_sector", 6)))
    w_prob = float(getattr(cfg, "v196_seed_path_prob_weight", 1.0))
    w_far = float(getattr(cfg, "v196_seed_path_far_weight", 0.35))
    ref_mm = float(getattr(cfg, "v196_seed_path_far_ref_mm", 6.0))

    groups_by_sector: Dict[int, np.ndarray] = {}
    for sec in sorted(set(int(sector_id[int(i)]) for i in seed_idx.tolist())):
        cand = seed_idx[sector_id[seed_idx] == sec]
        if len(cand) == 0:
            continue
        cand = cand[np.argsort(-probs[cand], kind="mergesort")[:max_per_sector]]
        groups_by_sector[int(sec)] = cand.astype(np.int64)
    if len(groups_by_sector) <= 1:
        return seed_idx[:1].astype(np.int64)

    uniq_sec = np.asarray(sorted(groups_by_sector.keys()), dtype=np.int32)
    gaps = []
    for i, sec in enumerate(uniq_sec.tolist()):
        nxt = int(uniq_sec[(i + 1) % len(uniq_sec)])
        gaps.append(_v196_forward_sector_distance(int(sec), nxt, int(sectors)))
    break_i = int(np.argmax(gaps))
    ordered_sec = list(uniq_sec[(break_i + 1):]) + list(uniq_sec[:(break_i + 1)])
    groups = [groups_by_sector[int(sec)] for sec in ordered_sec]

    costs = np.asarray([w_prob * (1.0 - float(probs[int(c)])) for c in groups[0]], dtype=np.float64)
    parents: List[np.ndarray] = []
    for gi in range(1, len(groups)):
        prev = groups[gi - 1]
        cur = groups[gi]
        new_costs = np.full((len(cur),), np.inf, dtype=np.float64)
        parent = np.full((len(cur),), -1, dtype=np.int64)
        for cj, c in enumerate(cur):
            d_mm = np.linalg.norm(xyz_norm[prev] - xyz_norm[int(c)][None, :], axis=1) * bs
            far = np.maximum(0.0, d_mm - ref_mm)
            edge_cost = d_mm + w_far * far * far / max(ref_mm, 1e-6)
            total = costs + edge_cost + w_prob * (1.0 - float(probs[int(c)]))
            pj = int(np.argmin(total))
            new_costs[cj] = float(total[pj])
            parent[cj] = pj
        costs = new_costs
        parents.append(parent)

    last_j = int(np.argmin(costs))
    out = [int(groups[-1][last_j])]
    for gi in range(len(groups) - 2, -1, -1):
        last_j = int(parents[gi][last_j])
        out.append(int(groups[gi][last_j]))
    out.reverse()
    return np.asarray(out, dtype=np.int64)


def _v196_point_to_closed_polyline_distance_np(xyz_norm: np.ndarray, path_norm: np.ndarray) -> np.ndarray:
    xyz_norm = np.asarray(xyz_norm, dtype=np.float32)
    path_norm = np.asarray(path_norm, dtype=np.float32)
    n = len(xyz_norm)
    k = len(path_norm)
    if n == 0:
        return np.zeros(0, dtype=np.float32)
    if k == 0:
        return np.full(n, 1e6, dtype=np.float32)
    if k == 1:
        return np.linalg.norm(xyz_norm - path_norm[0][None, :], axis=1).astype(np.float32)
    p0 = path_norm
    p1 = np.roll(path_norm, shift=-1, axis=0)
    vseg = p1 - p0
    vv = np.sum(vseg * vseg, axis=1)
    vv = np.maximum(vv, 1e-8)
    rel = xyz_norm[:, None, :] - p0[None, :, :]
    t = np.sum(rel * vseg[None, :, :], axis=2) / vv[None, :]
    t = np.clip(t, 0.0, 1.0)
    proj = p0[None, :, :] + t[:, :, None] * vseg[None, :, :]
    d2 = np.sum((xyz_norm[:, None, :] - proj) ** 2, axis=2)
    return np.sqrt(np.min(d2, axis=1)).astype(np.float32)


def _v196_top1_polar_guided_search(
    xyz_norm: np.ndarray,
    probs: np.ndarray,
    seed_idx: np.ndarray,
    cfg: Config,
    base_spacing: float,
) -> Dict[str, object]:
    """Final V1 search dispatcher: keep only the best beam_two_end sector-nearest branch.

    Earlier failed/unstable V19.6 branches are intentionally removed:
      - sector_nearest_link_360_forced_partial with tangent/lateral constraints;
      - greedy sector_nearest_only;
      - one-end beam sector_nearest_only.

    The final method uses a top1-anchored, two-end, 360-sector nearest-token beam
    search and then converts the real-token path to a corridor mask.
    """
    return _v196_sector_nearest_only_two_end_beam_search(
        xyz_norm=xyz_norm,
        probs=probs,
        seed_idx=seed_idx,
        cfg=cfg,
        base_spacing=base_spacing,
    )



def _v196_sector_nearest_only_two_end_beam_search(
    xyz_norm: np.ndarray,
    probs: np.ndarray,
    seed_idx: np.ndarray,
    cfg: Config,
    base_spacing: float,
) -> Dict[str, object]:
    """Bidirectional sector-nearest beam search across the open seed gap."""
    xyz_norm = np.asarray(xyz_norm, dtype=np.float32)
    probs = np.asarray(probs, dtype=np.float32)
    seed_idx = np.asarray(seed_idx, dtype=np.int64).reshape(-1)
    n = len(xyz_norm)
    bs = max(float(base_spacing), 1e-6)
    if n == 0 or len(seed_idx) < 2:
        return {
            "success": False,
            "path_idx": seed_idx.astype(np.int64),
            "ordered_seed_idx": seed_idx.astype(np.int64),
            "guide_xyz_norm": np.zeros((0, 3), dtype=np.float32),
            "rows": {"polar_success": 0, "polar_failure_reason": "too_few_seed_points"},
        }

    sectors = max(36, int(getattr(cfg, "v196_polar_num_sectors", 360)))
    max_step = max(1, int(getattr(cfg, "v196_polar_max_sector_step", 12)))
    max_empty_run = max(0, int(getattr(cfg, "v196_polar_max_empty_run", 24)))
    max_expanded = max(1000, int(getattr(cfg, "v196_polar_max_expanded_nodes", 60000)))
    beam_width = max(1, int(getattr(cfg, "v196_polar_beam_width", 12)))
    fanout = max(1, int(getattr(cfg, "v196_nearest_beam_fanout", 8)))
    radii_mm = _v196_parse_float_list(getattr(cfg, "v196_search_radii_mm", "2,4,6,8"), [2, 4, 6, 8])
    radii_mm = sorted([float(x) for x in radii_mm if float(x) > 0]) or [2.0, 4.0, 6.0, 8.0]

    center_mode = str(getattr(cfg, "v196_polar_center_mode", "existing"))
    center, u, v = _v196_polar_frame(xyz_norm, probs, center_mode=center_mode)
    theta = _v196_polar_theta(xyz_norm, center, u, v)
    rel = xyz_norm - center[None, :]
    polar_radius_mm = np.sqrt((rel @ u) ** 2 + (rel @ v) ** 2).astype(np.float32) * bs
    sector_id = np.floor(theta / (2.0 * np.pi) * float(sectors)).astype(np.int32)
    sector_id = np.clip(sector_id, 0, sectors - 1)

    seed_order = _v196_order_seed_by_theta(seed_idx, theta)
    seed_order = _v196_reduce_seed_chain_shortest(seed_order, xyz_norm, probs, sector_id, sectors, bs, cfg)
    if len(seed_order) < 2:
        return {
            "success": False,
            "path_idx": seed_order.astype(np.int64),
            "ordered_seed_idx": seed_order.astype(np.int64),
            "guide_xyz_norm": np.zeros((0, 3), dtype=np.float32),
            "rows": {"polar_success": 0, "polar_failure_reason": "too_few_ordered_seed_points"},
        }

    start_idx = int(seed_order[-1])
    target_idx = int(seed_order[0])
    start_sector = int(sector_id[start_idx])
    target_sector = int(sector_id[target_idx])
    total_steps = _v196_forward_sector_distance(start_sector, target_sector, sectors)
    if total_steps == 0:
        total_steps = sectors

    members = [np.where(sector_id == s)[0].astype(np.int64) for s in range(sectors)]
    seed_set = set(int(x) for x in seed_order.tolist())
    closure_radius_mm = float(getattr(cfg, "v196_closure_radius_mm", 8.0))
    min_progress_ratio = float(getattr(cfg, "v196_closure_min_progress_ratio", 0.80))
    w_sector = float(getattr(cfg, "v196_sector_weight", 0.10))
    w_prob = float(getattr(cfg, "v196_prob_weight", 0.0))
    w_radius_jump = float(getattr(cfg, "v196_radius_jump_weight", 0.0))
    w_meet = float(getattr(cfg, "v196_two_end_meet_weight", 0.0))

    def _merge(seed_chain: np.ndarray, left_gap: Sequence[int], right_gap: Sequence[int]) -> np.ndarray:
        left_arr = np.asarray(left_gap, dtype=np.int64)
        right_arr = np.asarray(right_gap, dtype=np.int64)
        gap = np.concatenate([left_arr, right_arr[::-1]]) if len(right_arr) else left_arr
        full = np.concatenate([seed_chain.astype(np.int64), gap[1:].astype(np.int64)]) if len(gap) > 1 else seed_chain.astype(np.int64)
        seen = set()
        out = []
        for ii in full.tolist():
            if int(ii) in seen:
                continue
            seen.add(int(ii))
            out.append(int(ii))
        return np.asarray(out, dtype=np.int64)

    def _coverage(lp: int, rp: int) -> int:
        return max(0, int(lp)) + max(0, int(total_steps - rp))

    def _endpoint_dist(li: int, ri: int) -> float:
        return float(np.linalg.norm(xyz_norm[int(li)] - xyz_norm[int(ri)])) * bs

    def _state_key(st):
        cost, lp, rp, li, ri, left_path, right_path, le, re, skipped, closed, meet_dist = st
        cov = _coverage(int(lp), int(rp))
        dist = float(meet_dist) if np.isfinite(meet_dist) else _endpoint_dist(int(li), int(ri))
        return (cov, -dist, len(left_path) + len(right_path), -float(cost))

    def _expand_side(st, side: str):
        cost, lp, rp, li, ri, left_path, right_path, le, re, skipped, closed, meet_dist = st
        lp = int(lp)
        rp = int(rp)
        li = int(li)
        ri = int(ri)
        used = set(int(x) for x in left_path) | set(int(x) for x in right_path)
        out = []
        cur_idx = li if side == "left" else ri
        other_idx = ri if side == "left" else li
        for radius_mm in radii_mm:
            local = []
            for delta in range(1, max_step + 1):
                if side == "left":
                    cand_progress = min(lp + delta, rp)
                    if cand_progress >= rp:
                        raw_cands = np.asarray([ri], dtype=np.int64)
                    else:
                        raw_cands = members[(start_sector + cand_progress) % sectors]
                else:
                    cand_progress = max(rp - delta, lp)
                    if cand_progress <= lp:
                        raw_cands = np.asarray([li], dtype=np.int64)
                    else:
                        raw_cands = members[(start_sector + cand_progress) % sectors]
                if len(raw_cands) == 0:
                    continue
                for cand in raw_cands:
                    cand = int(cand)
                    if cand in used and cand not in (li, ri):
                        continue
                    if cand in seed_set and cand not in (start_idx, target_idx, li, ri):
                        continue
                    edge_mm = float(np.linalg.norm(xyz_norm[cand] - xyz_norm[cur_idx])) * bs
                    if edge_mm < 1e-8 or edge_mm > float(radius_mm) + 1e-6:
                        continue
                    radius_jump_mm = abs(float(polar_radius_mm[cand]) - float(polar_radius_mm[cur_idx]))
                    meet_mm = float(np.linalg.norm(xyz_norm[cand] - xyz_norm[int(other_idx)])) * bs
                    cov_ratio = float(_coverage(cand_progress if side == "left" else lp, rp if side == "left" else cand_progress) / max(total_steps, 1))
                    meet_cost = w_meet * meet_mm if cov_ratio >= 0.50 else 0.0
                    edge_cost = edge_mm + w_sector * float(delta) + w_prob * (1.0 - float(probs[cand])) + w_radius_jump * radius_jump_mm + meet_cost
                    local.append((edge_cost, cand, int(cand_progress), max(0, delta - 1), meet_mm))
            if local:
                local.sort(key=lambda x: x[0])
                for edge_cost, cand, cand_progress, skip_inc, meet_mm in local[:fanout]:
                    if side == "left":
                        out.append((
                            float(cost + edge_cost), int(cand_progress), rp, int(cand), ri,
                            tuple(left_path) + (int(cand),), tuple(right_path), 0, re,
                            int(skipped + skip_inc), False, float(meet_mm),
                        ))
                    else:
                        out.append((
                            float(cost + edge_cost), lp, int(cand_progress), li, int(cand),
                            tuple(left_path), tuple(right_path) + (int(cand),), le, 0,
                            int(skipped + skip_inc), False, float(meet_mm),
                        ))
                break
        if not out:
            if side == "left" and int(le) + 1 <= max_empty_run and lp < rp:
                out.append((float(cost + 2.0 * w_sector), min(lp + 1, rp), rp, li, ri, tuple(left_path), tuple(right_path), int(le) + 1, re, int(skipped + 1), False, _endpoint_dist(li, ri)))
            if side == "right" and int(re) + 1 <= max_empty_run and rp > lp:
                out.append((float(cost + 2.0 * w_sector), lp, max(rp - 1, lp), li, ri, tuple(left_path), tuple(right_path), le, int(re) + 1, int(skipped + 1), False, _endpoint_dist(li, ri)))
        return out

    init = (0.0, 0, int(total_steps), start_idx, target_idx, (start_idx,), (target_idx,), 0, 0, 0, False, _endpoint_dist(start_idx, target_idx))
    beam = [init]
    best_partial = init
    success_states = []
    expanded = 0
    while beam and expanded < max_expanded:
        new_states = []
        for st in beam:
            cost, lp, rp, li, ri, left_path, right_path, le, re, skipped, closed, meet_dist = st
            cov_ratio = float(_coverage(int(lp), int(rp)) / max(total_steps, 1))
            meet_dist = _endpoint_dist(int(li), int(ri))
            if cov_ratio >= min_progress_ratio and meet_dist <= closure_radius_mm:
                closed_st = (float(cost), int(lp), int(rp), int(li), int(ri), tuple(left_path), tuple(right_path), int(le), int(re), int(skipped), True, float(meet_dist))
                success_states.append(closed_st)
                if _state_key(closed_st) > _state_key(best_partial):
                    best_partial = closed_st
                continue
            if _state_key(st) > _state_key(best_partial):
                best_partial = st
            if int(lp) >= int(rp):
                continue
            for side in ("left", "right"):
                for nxt in _expand_side(st, side):
                    expanded += 1
                    if _state_key(nxt) > _state_key(best_partial):
                        best_partial = nxt
                    new_states.append(nxt)
                    if expanded >= max_expanded:
                        break
                if expanded >= max_expanded:
                    break
        if success_states:
            break
        if not new_states:
            break
        new_states.sort(key=lambda st: (st[0] - 0.05 * _coverage(int(st[1]), int(st[2])) + 0.01 * _endpoint_dist(int(st[3]), int(st[4])), -_coverage(int(st[1]), int(st[2]))))
        beam = new_states[:beam_width]

    if success_states:
        success_states.sort(key=lambda st: (st[0], _endpoint_dist(int(st[3]), int(st[4])), -_coverage(int(st[1]), int(st[2]))))
        chosen = success_states[0]
        closed_success = 1
    else:
        chosen = best_partial
        closed_success = 0

    best_cost, lp, rp, li, ri, left_path, right_path, le, re, skipped, closed, meet_dist = chosen
    path_idx = _merge(seed_order, left_path, right_path)
    extra_tokens = max(0, int(len(path_idx) - len(seed_order)))
    accept_partial = bool(getattr(cfg, "v196_accept_partial_path", True))
    min_extra = int(getattr(cfg, "v196_min_partial_extra_tokens", 3))
    usable = bool(accept_partial and extra_tokens >= min_extra)
    success = bool(closed_success or usable)
    partial_success = int(usable and not closed_success)
    progress = _coverage(int(lp), int(rp))
    progress_ratio = float(progress / max(total_steps, 1))
    end_to_seed_min_dist_mm = float(meet_dist) if np.isfinite(meet_dist) else _endpoint_dist(int(li), int(ri))
    if len(path_idx) >= 2:
        edge = np.linalg.norm(np.diff(xyz_norm[path_idx], axis=0), axis=1) * bs
        max_edge_mm = float(np.max(edge)) if len(edge) else 0.0
        mean_edge_mm = float(np.mean(edge)) if len(edge) else 0.0
        path_length_mm = float(np.sum(edge)) if len(edge) else 0.0
    else:
        max_edge_mm = mean_edge_mm = path_length_mm = 0.0
    used_sectors = np.unique(sector_id[path_idx]) if len(path_idx) else np.zeros(0, dtype=np.int32)
    stop_reason = "two_end_closed" if closed_success else ("two_end_partial" if usable else "two_end_no_path")
    rows = dict(
        polar_success=int(success),
        polar_closed_success=int(closed_success),
        polar_closed_by_seed_reconnect=int(closed_success),
        polar_closure_dist_to_seed_mm=float(end_to_seed_min_dist_mm) if closed_success else np.nan,
        polar_progress_ratio_at_closure=progress_ratio if closed_success else np.nan,
        end_to_seed_min_dist_mm=float(end_to_seed_min_dist_mm),
        end_to_seed_nearest_index=int(ri),
        end_to_seed_nearest_is_old_seed=0,
        stop_reason=stop_reason,
        stop_sector=int(sector_id[int(li)]),
        last_sector=int(sector_id[int(ri)]),
        v196_polar_search_mode="sector_nearest_only",
        v196_nearest_only_strategy="beam_two_end",
        v196_polar_center_mode=center_mode,
        v196_radii_mm=",".join(str(float(x)).rstrip("0").rstrip(".") for x in radii_mm),
        v196_max_sector_step=int(max_step),
        v196_max_empty_run=int(max_empty_run),
        v196_candidate_score_mode=str(getattr(cfg, "v196_candidate_score_mode", "edge_sector_prob_radiusjump")),
        v196_prob_weight=float(w_prob),
        v196_sector_weight=float(w_sector),
        v196_radius_jump_weight=float(w_radius_jump),
        v196_closure_lookahead_weight=float(w_meet),
        v196_closure_radius_mm=closure_radius_mm,
        v196_closure_min_progress_ratio=min_progress_ratio,
        polar_partial_success=int(partial_success),
        polar_failure_reason="" if closed_success else ("partial_path_no_closed_cycle" if usable else "no_two_end_closed_path"),
        polar_search_mode="sector_nearest_only_beam_two_end",
        polar_num_sectors=int(sectors),
        polar_total_steps=int(total_steps),
        polar_best_progress_steps=int(progress),
        polar_progress_ratio=progress_ratio,
        polar_expanded_nodes=int(expanded),
        polar_path_tokens=int(len(path_idx)),
        polar_extra_tokens=int(extra_tokens),
        polar_guide_points=0,
        polar_used_sector_count=int(len(used_sectors)),
        polar_tokens_per_used_sector=float(len(path_idx) / max(len(used_sectors), 1)),
        polar_max_edge_mm=max_edge_mm,
        polar_mean_edge_mm=mean_edge_mm,
        polar_path_length_mm=path_length_mm,
        polar_seed_points=int(len(seed_idx)),
    )
    return {
        "success": bool(success),
        "partial": bool(partial_success),
        "path_idx": path_idx.astype(np.int64) if success else seed_order.astype(np.int64),
        "ordered_seed_idx": seed_order.astype(np.int64),
        "gap_path_idx": path_idx.astype(np.int64),
        "guide_xyz_norm": np.zeros((0, 3), dtype=np.float32),
        "rows": rows,
    }


def _v19_seed_retrieval_radii_mm(cfg: Config) -> List[float]:
    """Radii used only for seed-vs-GT retrieval diagnostics.

    This diagnostic answers a different question from final prediction quality:
    did the selected high-confidence seed component land on the real processing
    boundary, before any ring/corridor/path completion is considered?
    """
    raw = str(getattr(cfg, "seed_retrieval_radii_mm", "1,2,3"))
    vals: List[float] = []
    for part in raw.split(","):
        try:
            v = float(part.strip())
        except Exception:
            continue
        if np.isfinite(v) and v > 0:
            vals.append(float(v))
    if not vals:
        vals = [1.0, 2.0, 3.0]
    return vals


def _v19_seed_boundary_retrieval_metrics(
    seed_idx: np.ndarray,
    y: np.ndarray,
    xyz_norm: np.ndarray,
    probs: np.ndarray,
    base_spacing: float,
    cfg: Config,
) -> Dict[str, float]:
    """Evaluate whether a seed component retrieves real boundary tokens.

    The seed component is treated as an information-retrieval result:
      - retrieved set = tokens inside the seed component;
      - relevant set  = downsampled tokens with GT Label == 1.

    In addition to exact label overlap, the function reports nearest-neighbor
    distances in millimeters, because the source-anchored downsampled tokens and
    patch-label supervision may create small geometric offsets.
    """
    y = np.asarray(y, dtype=np.int64).reshape(-1)
    probs = np.asarray(probs, dtype=np.float32).reshape(-1)
    xyz_norm = np.asarray(xyz_norm, dtype=np.float32)
    n = int(len(y))
    seed_idx = np.asarray(seed_idx, dtype=np.int64).reshape(-1)
    seed_idx = np.unique(seed_idx[(seed_idx >= 0) & (seed_idx < n)]).astype(np.int64)
    gt_idx = np.where(y > 0)[0].astype(np.int64)
    total_gt = int(len(gt_idx))
    total_seed = int(len(seed_idx))

    tp = int(np.sum(y[seed_idx] > 0)) if total_seed else 0
    fp = int(total_seed - tp)
    fn = int(max(total_gt - tp, 0))
    precision = float(tp / total_seed) if total_seed > 0 else 0.0
    recall = float(tp / total_gt) if total_gt > 0 else 0.0
    denom = total_seed + total_gt - tp
    iou = float(tp / denom) if denom > 0 else 0.0
    f1 = float(2.0 * precision * recall / (precision + recall)) if (precision + recall) > 0 else 0.0

    row: Dict[str, float] = {
        "seed_points": int(total_seed),
        "seed_gt_positive_points": int(tp),
        "seed_gt_false_positive_points": int(fp),
        "seed_gt_false_negative_points": int(fn),
        "gt_total_points": int(total_gt),
        "seed_gt_precision": precision,
        "seed_gt_recall": recall,
        "seed_gt_iou": iou,
        "seed_gt_f1": f1,
        "seed_mean_prob": float(np.mean(probs[seed_idx])) if total_seed else 0.0,
        "seed_p90_prob": float(np.quantile(probs[seed_idx], 0.90)) if total_seed else 0.0,
    }

    # Optional patch-level positive ratio, when present in the downsampled cache.
    row["seed_label_overlap_ratio"] = precision

    bs = max(float(base_spacing), 1e-6)
    radii = _v19_seed_retrieval_radii_mm(cfg)
    if total_seed > 0 and total_gt > 0 and len(xyz_norm) == n:
        seed_pts = xyz_norm[seed_idx]
        gt_pts = xyz_norm[gt_idx]
        gt_tree = cKDTree(gt_pts)
        seed_tree = cKDTree(seed_pts)
        seed_to_gt_norm, _ = gt_tree.query(seed_pts, k=1)
        gt_to_seed_norm, _ = seed_tree.query(gt_pts, k=1)
        seed_to_gt_mm = np.asarray(seed_to_gt_norm, dtype=np.float32) * bs
        gt_to_seed_mm = np.asarray(gt_to_seed_norm, dtype=np.float32) * bs
        row.update({
            "seed_to_gt_mean_mm": float(np.mean(seed_to_gt_mm)),
            "seed_to_gt_p50_mm": float(np.quantile(seed_to_gt_mm, 0.50)),
            "seed_to_gt_p90_mm": float(np.quantile(seed_to_gt_mm, 0.90)),
            "seed_to_gt_max_mm": float(np.max(seed_to_gt_mm)),
            "gt_to_seed_mean_mm": float(np.mean(gt_to_seed_mm)),
            "gt_to_seed_p50_mm": float(np.quantile(gt_to_seed_mm, 0.50)),
            "gt_to_seed_p90_mm": float(np.quantile(gt_to_seed_mm, 0.90)),
            "gt_to_seed_max_mm": float(np.max(gt_to_seed_mm)),
        })
        for r_mm in radii:
            key = str(float(r_mm)).replace(".", "p").rstrip("0").rstrip("p")
            row[f"seed_near_gt_{key}mm_ratio"] = float(np.mean(seed_to_gt_mm <= float(r_mm)))
            row[f"gt_covered_by_seed_{key}mm_ratio"] = float(np.mean(gt_to_seed_mm <= float(r_mm)))
    else:
        row.update({
            "seed_to_gt_mean_mm": np.nan,
            "seed_to_gt_p50_mm": np.nan,
            "seed_to_gt_p90_mm": np.nan,
            "seed_to_gt_max_mm": np.nan,
            "gt_to_seed_mean_mm": np.nan,
            "gt_to_seed_p50_mm": np.nan,
            "gt_to_seed_p90_mm": np.nan,
            "gt_to_seed_max_mm": np.nan,
        })
        for r_mm in radii:
            key = str(float(r_mm)).replace(".", "p").rstrip("0").rstrip("p")
            row[f"seed_near_gt_{key}mm_ratio"] = np.nan
            row[f"gt_covered_by_seed_{key}mm_ratio"] = np.nan

    strict_prec_thr = float(getattr(cfg, "seed_boundary_precision_threshold", 0.50))
    near_radius = float(getattr(cfg, "seed_boundary_near_radius_mm", 2.0))
    near_thr = float(getattr(cfg, "seed_boundary_near_ratio_threshold", 0.70))
    near_key = str(float(near_radius)).replace(".", "p").rstrip("0").rstrip("p")
    near_ratio = float(row.get(f"seed_near_gt_{near_key}mm_ratio", np.nan))
    row["seed_boundary_precision_threshold"] = strict_prec_thr
    row["seed_boundary_near_radius_mm"] = near_radius
    row["seed_boundary_near_ratio_threshold"] = near_thr
    row["seed_is_actual_boundary_by_label"] = int(total_seed > 0 and precision >= strict_prec_thr)
    row["seed_is_actual_boundary_by_distance"] = int(total_seed > 0 and np.isfinite(near_ratio) and near_ratio >= near_thr)
    row["seed_is_actual_boundary"] = int(bool(row["seed_is_actual_boundary_by_label"] or row["seed_is_actual_boundary_by_distance"]))
    return row


def _v19_seed_boundary_retrieval_rows(
    record: Dict[str, object],
    selected_idx: np.ndarray,
    top_seed_components: List[np.ndarray],
    top_seed_rows: List[Dict[str, float]],
    cfg: Config,
) -> List[Dict[str, object]]:
    """Create per-file, per-seed diagnostic rows.

    Rows are written later under summaries/05_seed_retrieval/.  They are purely
    diagnostic and never feed back into threshold selection or prediction.
    """
    ds = record.get("downsampled", {})
    y = np.asarray(ds.get("label", np.zeros(0, dtype=np.int64)), dtype=np.int64)
    xyz_norm = np.asarray(record.get("xyz3d_norm", np.zeros((len(y), 3), dtype=np.float32)), dtype=np.float32)
    probs = np.asarray(record.get("pt_evidence_prob", record.get("token_transformer_prob", np.zeros(len(y), dtype=np.float32))), dtype=np.float32)
    bs = float(record.get("base_spacing", estimate_base_spacing_from_ds_v14(ds)))
    base = {
        "sample_id": record.get("sample_id", ""),
        "domain": record.get("domain", ""),
        "split": record.get("split", ""),
        "subset": record.get("subset", ""),
        "tokens": int(len(y)),
        "gt_points": int(np.sum(y > 0)),
        "evidence_key": str(getattr(cfg, "contour_evidence_prob_key", "pt_evidence_prob")),
    }
    out: List[Dict[str, object]] = []
    selected_set = set(map(int, np.asarray(selected_idx, dtype=np.int64).reshape(-1).tolist()))
    # Evaluate ranked seed components independently.  Default is Top1/Top2/Top3;
    # increasing --seed_retrieval_topk only adds more diagnostic rows, it does not
    # change the selected seed component or final prediction.
    topk = min(int(getattr(cfg, "seed_retrieval_topk", 3)), len(top_seed_components))
    for rank in range(topk):
        comp = np.asarray(top_seed_components[rank], dtype=np.int64)
        meta = dict(top_seed_rows[rank]) if rank < len(top_seed_rows) else {}
        comp_set = set(map(int, comp.tolist()))
        inter = len(comp_set & selected_set)
        union = len(comp_set | selected_set)
        row: Dict[str, object] = dict(base)
        row.update({
            "seed_role": "ranked_seed_component",
            "seed_rank": int(rank + 1),          # old size-first rank
            "old_seed_rank": int(meta.get("old_seed_rank", rank + 1)),
            "purity_new_rank": int(meta.get("purity_new_rank", -1)),
            "is_new_selected_seed": int(meta.get("is_new_selected_seed", 0)),
            "selection_rank_mode": str(meta.get("selection_rank_mode", getattr(cfg, "v19_seed_rerank_mode", "top3_purity_first"))),
            "component_id": int(meta.get("component_id", -1)),
            "selected_component_overlap_points": int(inter),
            "selected_component_jaccard": float(inter / union) if union > 0 else 0.0,
            "is_selected_main_component": int(union > 0 and inter == len(comp_set) and len(comp_set) > 0),
            "component_score": float(meta.get("score", 0.0)),
            "component_effective_score": float(meta.get("effective_score", meta.get("score", 0.0))),
            "component_eligible": int(meta.get("eligible", 0)),
            "component_length_norm": float(meta.get("length", 0.0)),
            "component_width_norm": float(meta.get("width", 0.0)),
            "component_linearness": float(meta.get("linearness", 0.0)),
            "component_high_points": int(meta.get("high_points", 0)),
            "purity_proxy_score": float(meta.get("purity_proxy_score", np.nan)),
            "purity_q25_prob": float(meta.get("purity_q25_prob", np.nan)),
            "purity_q50_prob": float(meta.get("purity_q50_prob", np.nan)),
            "purity_mean_prob": float(meta.get("purity_mean_prob", np.nan)),
            "purity_prob_std": float(meta.get("purity_prob_std", np.nan)),
            "purity_width_mm": float(meta.get("purity_width_mm", np.nan)),
            "purity_width_penalty": float(meta.get("purity_width_penalty", np.nan)),
        })
        row.update(_v19_seed_boundary_retrieval_metrics(comp, y, xyz_norm, probs, bs, cfg))
        out.append(row)

    # Identify which old Top1/Top2/Top3 component became the final selected seed.
    selected_old_rank = -1
    selected_meta: Dict[str, float] = {}
    for rank in range(topk):
        comp = np.asarray(top_seed_components[rank], dtype=np.int64)
        comp_set = set(map(int, comp.tolist()))
        if len(comp_set) == len(selected_set) and len(comp_set & selected_set) == len(selected_set) and len(selected_set) > 0:
            selected_old_rank = int(rank + 1)
            selected_meta = dict(top_seed_rows[rank]) if rank < len(top_seed_rows) else {}
            break

    selected_row: Dict[str, object] = dict(base)
    selected_row.update({
        "seed_role": "selected_final_seed_set",
        "seed_rank": 0,
        "selected_from_old_seed_rank": int(selected_old_rank),
        "selection_rank_mode": str(selected_meta.get("selection_rank_mode", getattr(cfg, "v19_seed_rerank_mode", "top3_purity_first"))),
        "component_id": int(selected_meta.get("component_id", -1)),
        "selected_component_overlap_points": int(len(selected_set)),
        "selected_component_jaccard": 1.0 if len(selected_set) else 0.0,
        "is_selected_main_component": 1 if len(selected_set) else 0,
        "component_score": float(selected_meta.get("score", np.nan)),
        "component_effective_score": float(selected_meta.get("effective_score", np.nan)),
        "component_eligible": int(selected_meta.get("eligible", 0)) if selected_meta else np.nan,
        "component_length_norm": float(selected_meta.get("length", np.nan)),
        "component_width_norm": float(selected_meta.get("width", np.nan)),
        "component_linearness": float(selected_meta.get("linearness", np.nan)),
        "component_high_points": int(selected_meta.get("high_points", 0)) if selected_meta else np.nan,
        "purity_proxy_score": float(selected_meta.get("purity_proxy_score", np.nan)),
        "purity_q25_prob": float(selected_meta.get("purity_q25_prob", np.nan)),
        "purity_q50_prob": float(selected_meta.get("purity_q50_prob", np.nan)),
        "purity_mean_prob": float(selected_meta.get("purity_mean_prob", np.nan)),
        "purity_prob_std": float(selected_meta.get("purity_prob_std", np.nan)),
        "purity_width_mm": float(selected_meta.get("purity_width_mm", np.nan)),
        "purity_width_penalty": float(selected_meta.get("purity_width_penalty", np.nan)),
    })
    selected_row.update(_v19_seed_boundary_retrieval_metrics(np.asarray(selected_idx, dtype=np.int64), y, xyz_norm, probs, bs, cfg))
    # Record whether the ranking rule picked the seed with the best GT overlap among retrieved candidates.
    ranked = [r for r in out if r.get("seed_role") == "ranked_seed_component"]
    if ranked:
        best_by_iou = max(ranked, key=lambda rr: (float(rr.get("seed_gt_iou", 0.0)), float(rr.get("seed_gt_precision", 0.0)), float(rr.get("seed_gt_recall", 0.0))))
        selected_row["best_seed_rank_by_gt_iou"] = int(best_by_iou.get("seed_rank", -1))
        selected_row["best_seed_gt_iou"] = float(best_by_iou.get("seed_gt_iou", 0.0))
        selected_row["best_seed_gt_precision"] = float(best_by_iou.get("seed_gt_precision", 0.0))
        selected_row["best_seed_gt_recall"] = float(best_by_iou.get("seed_gt_recall", 0.0))
        selected_row["selected_minus_best_seed_gt_iou"] = float(selected_row.get("seed_gt_iou", 0.0)) - float(best_by_iou.get("seed_gt_iou", 0.0))
        selected_row["selected_is_best_seed_by_gt_iou"] = int(int(best_by_iou.get("seed_rank", -999)) == int(selected_row.get("selected_from_old_seed_rank", -998)))
    else:
        selected_row["best_seed_rank_by_gt_iou"] = -1
        selected_row["best_seed_gt_iou"] = 0.0
        selected_row["best_seed_gt_precision"] = 0.0
        selected_row["best_seed_gt_recall"] = 0.0
        selected_row["selected_minus_best_seed_gt_iou"] = 0.0
        selected_row["selected_is_best_seed_by_gt_iou"] = 0
    out.append(selected_row)
    return out


def collect_seed_retrieval_rows(records: List[Dict[str, object]]) -> List[Dict[str, object]]:
    rows: List[Dict[str, object]] = []
    for r in records:
        for row in r.get("seed_retrieval_rows", []):
            rows.append(dict(row))
    return rows

def _v19_hard_constrained_extract_one(record: Dict[str, object], cfg: Config) -> Dict[str, object]:
    ds = record.get("downsampled", {})
    xyz = np.asarray(ds.get("xyz", np.zeros((0, 3), dtype=np.float32)), dtype=np.float32)
    y = np.asarray(ds.get("label", np.zeros((0,), dtype=np.int64)), dtype=np.int64)
    xyz_norm = np.asarray(record.get("xyz3d_norm", np.zeros((len(y), 3), dtype=np.float32)), dtype=np.float32)
    probs = np.asarray(record.get("pt_evidence_prob", record.get("token_transformer_prob", np.zeros(len(y), dtype=np.float32))), dtype=np.float32)
    n = int(len(y))
    if n == 0:
        return {"prob": np.zeros(0, dtype=np.float32), "rows": {}, "selected_idx": np.zeros(0, dtype=np.int64), "ordered_idx": np.zeros(0, dtype=np.int64)}
    bs = float(record.get("base_spacing", estimate_base_spacing_from_ds_v14(ds)))
    high_thr = float(getattr(cfg, "v19_high_threshold", 0.70))
    weak_thr = float(getattr(cfg, "v19_weak_threshold", 0.25))
    max_step_factor = float(getattr(cfg, "v19_max_step_factor", 8.0))
    max_step_mm = float(getattr(cfg, "v19_max_step_mm", 3.0))
    max_step_norm = min(max_step_factor, max_step_mm / max(bs, 1e-6)) if max_step_mm > 0 else max_step_factor
    max_bridge_factor = float(getattr(cfg, "v19_max_bridge_gap_factor", 16.0))
    max_bridge_mm = float(getattr(cfg, "v19_max_bridge_gap_mm", 6.0))
    max_bridge_norm = min(max_bridge_factor, max_bridge_mm / max(bs, 1e-6)) if max_bridge_mm > 0 else max_bridge_factor
    fallback_topk = int(getattr(cfg, "v19_fallback_topk", 96))
    comps, weak_idx = _v19_build_components(xyz_norm, probs, weak_thr, max_step_norm, fallback_topk)
    selected_idx, main_m, comp_rows, top_seed_components, top_seed_rows = _v19_select_main_component(xyz_norm, probs, comps, cfg, base_spacing=bs)

    # Optional conservative local inclusion: nearby components may be added only if their nearest point is within max_bridge.
    if bool(getattr(cfg, "v19_include_nearby_components", False)) and len(selected_idx) > 0:
        sel_set = set(map(int, selected_idx.tolist()))
        sel_pts = xyz_norm[selected_idx]
        sel_tree = cKDTree(sel_pts)
        high_thr = float(getattr(cfg, "v19_high_threshold", 0.70))
        for comp in comps:
            if all(int(i) in sel_set for i in comp):
                continue
            m = _v19_component_metrics(xyz_norm[comp], probs[comp], high_thr)
            if m["points"] < int(getattr(cfg, "v19_nearby_min_points", 8)) or m["high_points"] < int(getattr(cfg, "v19_nearby_min_high_points", 3)):
                continue
            d, _ = sel_tree.query(xyz_norm[comp], k=1)
            if float(np.min(d)) <= max_bridge_norm:
                for i in comp:
                    sel_set.add(int(i))
                selected_idx = np.asarray(sorted(sel_set), dtype=np.int64)
                sel_pts = xyz_norm[selected_idx]
                sel_tree = cKDTree(sel_pts)

    seed_ordered_idx, order_stats = _v19_order_connected_component(xyz_norm, selected_idx, probs, max_step_norm)

    # V19.6: optional top1-anchored polar ordered directional search.
    # The selected new_top1 seed remains the hard anchor; virtual guide points only
    # steer the search and never become final anchors.  If search fails, fall back
    # to the selected seed component.
    polar_res: Dict[str, object] = {"success": False, "rows": {"polar_success": 0, "polar_failure_reason": "disabled"}}
    support_idx = np.asarray(selected_idx, dtype=np.int64)
    ordered_idx = np.asarray(seed_ordered_idx, dtype=np.int64)
    if bool(getattr(cfg, "v196_enable_polar_search", False)) and len(selected_idx) >= 2:
        polar_res = _v196_top1_polar_guided_search(xyz_norm, probs, selected_idx, cfg, base_spacing=bs)
        if bool(polar_res.get("success", False)):
            path_idx = np.asarray(polar_res.get("path_idx", selected_idx), dtype=np.int64)
            if len(path_idx) >= len(selected_idx):
                support_idx = path_idx
                ordered_idx = path_idx

    # Probability/mask: fixed physical corridor around the searched path if polar
    # search succeeds; otherwise around the selected high-precision seed.  The
    # searched path is made only of real downsampled token indices.
    corridor_distance_mode = str(getattr(cfg, "v196_corridor_distance_mode", "polyline"))
    if len(support_idx) > 0:
        if bool(polar_res.get("success", False)) and len(ordered_idx) >= 2 and corridor_distance_mode == "polyline":
            d = _v196_point_to_closed_polyline_distance_np(xyz_norm, xyz_norm[ordered_idx]).astype(np.float32)
        else:
            tree = cKDTree(xyz_norm[support_idx])
            d, _ = tree.query(xyz_norm, k=1)
            d = d.astype(np.float32)
    else:
        d = np.full(n, 1e6, dtype=np.float32)
    width = float(getattr(cfg, "contour_fixed_width_factor", 2.0))
    tau = max(float(getattr(cfg, "contour_tau_factor", 0.25)), 1e-4)
    prob = 1.0 / (1.0 + np.exp((d - width) / tau))
    final_prob_mode = str(getattr(cfg, "v196_final_prob_mode", "corridor"))
    if final_prob_mode == "corridor_times_evidence":
        prob = prob * np.clip(probs, 0.0, 1.0)
    elif final_prob_mode == "corridor_soft_evidence_gate":
        floor = float(getattr(cfg, "v196_evidence_gate_floor", 0.35))
        floor = float(np.clip(floor, 0.0, 1.0))
        prob = prob * (floor + (1.0 - floor) * np.clip(probs, 0.0, 1.0))
    elif final_prob_mode == "corridor_or_high_evidence":
        thr = float(getattr(cfg, "v196_evidence_union_threshold", 0.85))
        prob = np.maximum(prob, np.where(probs >= thr, probs, 0.0))
    elif final_prob_mode == "corridor_gate_or_high_evidence":
        floor = float(getattr(cfg, "v196_evidence_gate_floor", 0.35))
        floor = float(np.clip(floor, 0.0, 1.0))
        thr = float(getattr(cfg, "v196_evidence_union_threshold", 0.85))
        gated = prob * (floor + (1.0 - floor) * np.clip(probs, 0.0, 1.0))
        prob = np.maximum(gated, np.where(probs >= thr, probs, 0.0))
    # Selected/search path line points are visible in the trajectory mask.
    if len(support_idx) > 0:
        prob[support_idx] = np.maximum(prob[support_idx], 1.0)

    # Diagnostics.
    closed_gap = 0.0
    closed_success = False
    if len(ordered_idx) >= 2:
        closed_gap = float(np.linalg.norm(xyz_norm[ordered_idx[0]] - xyz_norm[ordered_idx[-1]]))
        closed_success = bool(closed_gap <= max_bridge_norm)
    high_total = int(np.sum(probs >= high_thr))
    rejected_high = int(len(set(np.where(probs >= high_thr)[0].tolist()) - set(selected_idx.tolist()))) if len(selected_idx) else high_total
    rows = dict(
        sample_id=record.get("sample_id", ""), domain=record.get("domain", ""), split=record.get("split", ""), subset=record.get("subset", ""),
        tokens=n, gt_points=int(np.sum(y)), high_threshold=high_thr, weak_threshold=weak_thr,
        max_step_norm=float(max_step_norm), max_step_mm=float(max_step_norm * bs), max_bridge_norm=float(max_bridge_norm), max_bridge_mm=float(max_bridge_norm * bs),
        num_weak_candidates=int(len(weak_idx)), num_components=int(len(comps)), main_component_points=int(len(selected_idx)), main_component_high_points=int(main_m.get("high_points", 0)),
        main_component_mean_prob=float(main_m.get("mean_prob", 0.0)), main_component_high_mean_prob=float(main_m.get("high_mean_prob", 0.0)),
        main_component_length_norm=float(main_m.get("length", 0.0)), main_component_width_norm=float(main_m.get("width", 0.0)), main_component_linearness=float(main_m.get("linearness", 0.0)),
        seed_selection_rank_mode=str(main_m.get("selection_rank_mode", getattr(cfg, "v19_seed_rerank_mode", "top3_purity_first"))),
        selected_from_old_seed_rank=int(main_m.get("selected_from_old_seed_rank", 1)),
        selected_by_purity_rerank=int(main_m.get("selected_by_purity_rerank", 0)),
        selected_purity_proxy_score=float(main_m.get("purity_proxy_score", np.nan)),
        selected_purity_q25_prob=float(main_m.get("purity_q25_prob", np.nan)),
        selected_purity_mean_prob=float(main_m.get("purity_mean_prob", np.nan)),
        selected_purity_width_mm=float(main_m.get("purity_width_mm", np.nan)),
        rejected_high_prob_points=int(rejected_high), max_edge_norm=float(order_stats.get("max_edge_norm", 0.0)), max_edge_mm=float(order_stats.get("max_edge_norm", 0.0) * bs),
        num_illegal_edges=int(order_stats.get("illegal_edges", 0)), num_visual_segments=int(order_stats.get("num_segments", 0)), max_gap_norm=float(order_stats.get("max_gap_norm", 0.0)), max_gap_mm=float(order_stats.get("max_gap_norm", 0.0) * bs),
        closed_success=int(closed_success), closure_gap_norm=float(closed_gap), closure_gap_mm=float(closed_gap * bs),
        mean_final_prob=float(np.mean(prob)) if len(prob) else 0.0, mean_pt_evidence_prob=float(np.mean(probs)) if len(probs) else 0.0,
        mean_ring_trajectory_prob=float(np.mean(prob)) if len(prob) else 0.0,
        v196_final_prob_mode=final_prob_mode,
        v196_corridor_distance_mode=corridor_distance_mode,
        v196_evidence_union_threshold=float(getattr(cfg, "v196_evidence_union_threshold", 0.85)),
        v196_evidence_gate_floor=float(getattr(cfg, "v196_evidence_gate_floor", 0.35)),
    )
    # Add V19.6 polar-search diagnostics to the same geometry summary row.
    polar_rows = dict(polar_res.get("rows", {})) if isinstance(polar_res, dict) else {}
    for pk, pv in polar_rows.items():
        rows[pk] = pv
    rows["polar_enabled"] = int(bool(getattr(cfg, "v196_enable_polar_search", False)))
