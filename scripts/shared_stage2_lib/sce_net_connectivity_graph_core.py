            r["contour_anchor_confidence"] = np.asarray(r.get("pt_evidence_prob", np.zeros(len(xyz), dtype=np.float32)))[ctrl_idx].astype(np.float32) if len(ctrl_idx) else np.zeros(0, dtype=np.float32)
