def _top_seed_clusters_rgb_label(n: int, top_seed_components: object, topk: int = 3) -> Tuple[np.ndarray, np.ndarray]:
    """Return RGB/Label map for top seed high-confidence components.

    Label convention:
      0 = not in top seed components / blue
      1 = top1 seed component / yellow
      2 = top2 seed component / magenta
      3 = top3 seed component / cyan
    """
    n = int(n)
    rgb = np.zeros((n, 3), dtype=np.uint8)
    rgb[:] = np.array([0, 0, 255], dtype=np.uint8)
    label = np.zeros((n,), dtype=np.int32)
    colors = [
        np.array([255, 220, 0], dtype=np.uint8),
        np.array([255, 0, 255], dtype=np.uint8),
        np.array([0, 255, 255], dtype=np.uint8),
    ]
    comps = top_seed_components if isinstance(top_seed_components, (list, tuple)) else []
    for rank in reversed(range(min(int(topk), len(comps), 3))):
        idx = np.asarray(comps[rank], dtype=np.int64)
        idx = idx[(idx >= 0) & (idx < n)]
        if len(idx) == 0:
            continue
        rgb[idx] = colors[rank]
        label[idx] = int(rank + 1)
    return rgb, label


def _top_seed_overlay_points(xyz: np.ndarray, top_seed_components: object, topk: int = 3) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return duplicate colored points for overlay visualization of top seed components."""
    xyz = np.asarray(xyz, dtype=np.float32)
    if len(xyz) == 0:
        return np.zeros((0, 3), dtype=np.float32), np.zeros((0, 3), dtype=np.uint8), np.zeros((0,), dtype=np.int32)
    colors = [
        np.array([255, 220, 0], dtype=np.uint8),
        np.array([255, 0, 255], dtype=np.uint8),
        np.array([0, 255, 255], dtype=np.uint8),
    ]
    comps = top_seed_components if isinstance(top_seed_components, (list, tuple)) else []
    pts_list: List[np.ndarray] = []
    rgb_list: List[np.ndarray] = []
    lab_list: List[np.ndarray] = []
    for rank in range(min(int(topk), len(comps), 3)):
        idx = np.asarray(comps[rank], dtype=np.int64)
        idx = idx[(idx >= 0) & (idx < len(xyz))]
        if len(idx) == 0:
            continue
        pts_list.append(xyz[idx].astype(np.float32))
        rgb_list.append(np.tile(colors[rank][None, :], (len(idx), 1)).astype(np.uint8))
        lab_list.append(np.full((len(idx),), 21 + rank, dtype=np.int32))
    if not pts_list:
        return np.zeros((0, 3), dtype=np.float32), np.zeros((0, 3), dtype=np.uint8), np.zeros((0,), dtype=np.int32)
    return np.vstack(pts_list).astype(np.float32), np.vstack(rgb_list).astype(np.uint8), np.concatenate(lab_list).astype(np.int32)

def export_closed_contour_3d_visualization_pack(
    record: Dict[str, object],
    pt_threshold: float,
    contour_threshold: float,
    cfg: Config,
) -> bool:
    """Export V19 polar-corridor/PT visualization files.

    CloudCompare-friendly TXT: X Y Z R G B Label.
    Label meanings:
      0 TN / blue, 1 TP / yellow, 2 FP / red, 3 FN / green in error maps;
      10 dense contour samples, 11 control points in overlay maps.
    """
    ds = record.get("downsampled", {})
    xyz = np.asarray(ds.get("xyz", np.zeros((0, 3), dtype=np.float32)), dtype=np.float32)
    y = np.asarray(ds.get("label", np.zeros(0, dtype=np.int64)), dtype=np.int32)
    if len(xyz) == 0 or len(y) == 0:
        return False

    pt_prob = np.asarray(record.get("pt_evidence_prob", record.get("token_transformer_prob", np.zeros(len(y)))), dtype=np.float32)
    final_prob = np.asarray(record.get("contour_token_prob", np.zeros(len(y))), dtype=np.float32)
    corridor_prob = np.asarray(record.get("ring_trajectory_prob", record.get("contour_corridor_prob", np.zeros(len(y)))), dtype=np.float32)
    control_xyz = np.asarray(record.get("contour_control_xyz", np.zeros((0, 3), dtype=np.float32)), dtype=np.float32)
    width_factor = np.asarray(record.get("contour_width_factor", np.zeros(len(control_xyz), dtype=np.float32)), dtype=np.float32)

    pt_pred = pt_prob >= float(pt_threshold)
    final_pred = final_prob >= float(contour_threshold)
    corridor_mask = corridor_prob >= 0.5

    subset_name = str(record.get("subset", "unknown"))
    if str(record.get("domain", "")) == "real" and str(record.get("split", "")) == "test":
        vis_group = subset_name
    else:
        vis_group = f"{record.get('domain','')}_{record.get('split','')}_{subset_name}"
    prefix = str(record.get("sample_id", "sample"))
    root = os.path.join(cfg.output_root, PAPER_VIS_OUTPUT_DIRNAME, vis_group)

    # 00: GT red/blue.
    _write_xyz_rgb_label(
        os.path.join(root, "00_gt", prefix + "_00.txt"),
        xyz, _simple_rgb_red_blue(y.astype(bool)), y,
    )

    # 01: frozen PT token evidence prediction.
    _write_xyz_rgb_label(
        os.path.join(root, "01_pt", prefix + "_01.txt"),
        xyz, _simple_rgb_red_blue(pt_pred), pt_pred.astype(np.int32),
    )

    # 01b: top-3 seed high-confidence components used by the deterministic extractor.
    seed_topk = max(1, int(max(getattr(cfg, "contour_vis_seed_topk", 3), getattr(cfg, "seed_retrieval_topk", 10))))
    seed_rgb, seed_label = _top_seed_clusters_rgb_label(len(xyz), record.get("top_seed_components", []), topk=seed_topk)
    _write_xyz_rgb_label(
        os.path.join(root, "01b_seed", prefix + "_01b.txt"),
        xyz, seed_rgb, seed_label,
    )

    # 02: learned 3D corridor mask alone.
    _write_xyz_rgb_label(
        os.path.join(root, "02_mask", prefix + "_02.txt"),
        xyz, _simple_rgb_red_blue(corridor_mask), corridor_mask.astype(np.int32),
    )

    # 03: final fused prediction.
    _write_xyz_rgb_label(
        os.path.join(root, "03_final", prefix + "_03.txt"),
        xyz, _simple_rgb_red_blue(final_pred), final_pred.astype(np.int32),
    )

    # 04: final TP/FP/FN/TN error map.
    err_rgb, err_label = _simple_error_rgb_label(y, final_pred)
    _write_xyz_rgb_label(
        os.path.join(root, "04_err", prefix + "_04.txt"),
        xyz, err_rgb, err_label,
    )

    # 05/06: predicted 3D contour samples and controls.
    if len(control_xyz) > 0:
        curve_xyz = np.asarray(record.get("v19_hard_trajectory_xyz", np.zeros((0, 3), dtype=np.float32)), dtype=np.float32)
        if len(curve_xyz) == 0:
            curve_xyz = dense_sample_closed_contour_3d_np(control_xyz, samples_per_segment=int(getattr(cfg, "contour_vis_samples_per_segment", 16)))
        curve_rgb = np.tile(np.array([[255, 220, 0]], dtype=np.uint8), (len(curve_xyz), 1))
        curve_label = np.full(len(curve_xyz), 10, dtype=np.int32)
        _write_xyz_rgb_label(
            os.path.join(root, "05_curve", prefix + "_05.txt"),
            curve_xyz, curve_rgb, curve_label,
        )

        ctrl_rgb = np.tile(np.array([[255, 255, 255]], dtype=np.uint8), (len(control_xyz), 1))
        ctrl_label = np.round(width_factor * 100.0).astype(np.int32) if len(width_factor) == len(control_xyz) else np.full(len(control_xyz), 11, dtype=np.int32)
        _write_xyz_rgb_label(
            os.path.join(root, "06_width", prefix + "_06.txt"),
            control_xyz, ctrl_rgb, ctrl_label,
        )

        # 06b: anchor tokens selected by the contour queries.
        anchor_idx = np.asarray(record.get("contour_anchor_index", np.zeros(0, dtype=np.int64)), dtype=np.int64)
        if len(anchor_idx) > 0 and len(xyz) > 0:
            anchor_idx = np.clip(anchor_idx, 0, len(xyz) - 1)
            anchor_xyz = xyz[anchor_idx]
            anchor_conf = np.asarray(record.get("contour_anchor_confidence", np.ones(len(anchor_idx), dtype=np.float32)), dtype=np.float32)
            anchor_rgb = np.tile(np.array([[255, 255, 255]], dtype=np.uint8), (len(anchor_xyz), 1))
            anchor_label = np.round(anchor_conf * 1000.0).astype(np.int32)
            _write_xyz_rgb_label(
                os.path.join(root, "06b_anchors", prefix + "_06b.txt"),
                anchor_xyz, anchor_rgb, anchor_label,
            )

        # 06c: dense trajectory slot anchors.
        traj_xyz = np.asarray(record.get("ring_trajectory_anchor_xyz", np.zeros((0, 3), dtype=np.float32)), dtype=np.float32)
        if len(traj_xyz) > 0:
            traj_rgb = np.tile(np.array([[255, 0, 255]], dtype=np.uint8), (len(traj_xyz), 1))
            traj_label = np.full(len(traj_xyz), 12, dtype=np.int32)
            _write_xyz_rgb_label(
                os.path.join(root, "06c_slots", prefix + "_06c.txt"),
                traj_xyz, traj_rgb, traj_label,
            )
        else:
            traj_rgb = np.zeros((0, 3), dtype=np.uint8)
            traj_label = np.zeros((0,), dtype=np.int32)

        # 06d/06e: V19.6 polar directional search visualization.
        polar_path_idx = np.asarray(record.get("polar_path_index", np.zeros(0, dtype=np.int64)), dtype=np.int64)
        polar_seed_idx = np.asarray(record.get("polar_ordered_seed_index", np.zeros(0, dtype=np.int64)), dtype=np.int64)
        polar_guide_xyz = np.asarray(record.get("polar_guide_xyz", np.zeros((0, 3), dtype=np.float32)), dtype=np.float32)
        polar_path_xyz = xyz[np.clip(polar_path_idx, 0, len(xyz) - 1)] if len(polar_path_idx) and len(xyz) else np.zeros((0, 3), dtype=np.float32)
        polar_seed_xyz = xyz[np.clip(polar_seed_idx, 0, len(xyz) - 1)] if len(polar_seed_idx) and len(xyz) else np.zeros((0, 3), dtype=np.float32)
        if len(polar_path_xyz) or len(polar_seed_xyz) or len(polar_guide_xyz):
            pp_xyz = np.vstack([polar_path_xyz, polar_seed_xyz, polar_guide_xyz]).astype(np.float32)
            pp_rgb = np.vstack([
                np.tile(np.array([[0, 255, 0]], dtype=np.uint8), (len(polar_path_xyz), 1)),
                np.tile(np.array([[255, 255, 255]], dtype=np.uint8), (len(polar_seed_xyz), 1)),
                np.tile(np.array([[255, 160, 0]], dtype=np.uint8), (len(polar_guide_xyz), 1)),
            ])
            pp_label = np.concatenate([
                np.full(len(polar_path_xyz), 20, dtype=np.int32),
                np.full(len(polar_seed_xyz), 21, dtype=np.int32),
                np.full(len(polar_guide_xyz), 22, dtype=np.int32),
            ])
            _write_xyz_rgb_label(
                os.path.join(root, "06d_polar", prefix + "_06d.txt"),
                pp_xyz, pp_rgb, pp_label,
            )

            overlay_polar_xyz = np.vstack([xyz, polar_path_xyz, polar_seed_xyz, polar_guide_xyz]).astype(np.float32)
            overlay_polar_rgb = np.vstack([
                err_rgb.astype(np.uint8),
                np.tile(np.array([[0, 255, 0]], dtype=np.uint8), (len(polar_path_xyz), 1)),
                np.tile(np.array([[255, 255, 255]], dtype=np.uint8), (len(polar_seed_xyz), 1)),
                np.tile(np.array([[255, 160, 0]], dtype=np.uint8), (len(polar_guide_xyz), 1)),
            ])
            overlay_polar_label = np.concatenate([
                err_label.astype(np.int32),
                np.full(len(polar_path_xyz), 20, dtype=np.int32),
                np.full(len(polar_seed_xyz), 21, dtype=np.int32),
                np.full(len(polar_guide_xyz), 22, dtype=np.int32),
            ])
            _write_xyz_rgb_label(
                os.path.join(root, "08_overlay", prefix + "_08.txt"),
                overlay_polar_xyz, overlay_polar_rgb, overlay_polar_label,
            )

        # 07: overlay final error tokens + contour curve + controls + trajectory slot anchors.
        overlay_xyz = np.vstack([xyz, curve_xyz, control_xyz, traj_xyz]).astype(np.float32)
        overlay_rgb = np.vstack([
            err_rgb.astype(np.uint8),
            curve_rgb.astype(np.uint8),
            ctrl_rgb.astype(np.uint8),
            traj_rgb.astype(np.uint8),
        ])
        overlay_label = np.concatenate([
            err_label.astype(np.int32),
            np.full(len(curve_xyz), 10, dtype=np.int32),
            np.full(len(control_xyz), 11, dtype=np.int32),
            traj_label.astype(np.int32),
        ])
        _write_xyz_rgb_label(
            os.path.join(root, "07_overlay", prefix + "_07.txt"),
            overlay_xyz, overlay_rgb, overlay_label,
        )

        # 07b: overlay final error tokens + top-3 seed components + contour.
        seed_xyz, seed_rgb_overlay, seed_label_overlay = _top_seed_overlay_points(
            xyz, record.get("top_seed_components", []), topk=max(1, int(getattr(cfg, "contour_vis_seed_topk", 3)))
        )
        overlay2_xyz = np.vstack([xyz, seed_xyz, curve_xyz, control_xyz, traj_xyz]).astype(np.float32)
        overlay2_rgb = np.vstack([
            err_rgb.astype(np.uint8),
            seed_rgb_overlay.astype(np.uint8),
            curve_rgb.astype(np.uint8),
            ctrl_rgb.astype(np.uint8),
            traj_rgb.astype(np.uint8),
        ])
        overlay2_label = np.concatenate([
            err_label.astype(np.int32),
            seed_label_overlay.astype(np.int32),
            np.full(len(curve_xyz), 10, dtype=np.int32),
            np.full(len(control_xyz), 11, dtype=np.int32),
            traj_label.astype(np.int32),
        ])
        _write_xyz_rgb_label(
            os.path.join(root, "07b_overlay_seed", prefix + "_07b.txt"),
            overlay2_xyz, overlay2_rgb, overlay2_label,
        )
    return True


def export_closed_contour_3d_visualizations(
    records: List[Dict[str, object]],
    pt_threshold: float,
    contour_threshold: float,
    cfg: Config,
) -> None:
    """Export V19 polar-corridor visualization packs per split/subset."""
    if not bool(getattr(cfg, "export_paper_visualizations", True)):
        return
    limit = int(getattr(cfg, "contour_vis_files_per_subset", 5))
    export_all_real = bool(getattr(cfg, "contour_vis_export_all_real", True))
    if limit <= 0 and not export_all_real:
        return
    counters: Dict[str, int] = {}
    for r in records:
        key = f"{r.get('domain','')}_{r.get('split','')}_{r.get('subset','')}"
        is_real_test = (str(r.get("domain", "")) == "real" and str(r.get("split", "")) == "test")
