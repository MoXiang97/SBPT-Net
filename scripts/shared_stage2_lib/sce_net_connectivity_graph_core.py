def estimate_base_spacing(xyz: np.ndarray, sample_size: int = 8000) -> float:
    n = len(xyz)
    if n <= 1:
        return 1.0
    if n > sample_size:
        rng = np.random.default_rng(2026)
        idx = rng.choice(n, size=sample_size, replace=False)
        pts = xyz[idx]
    else:
        pts = xyz
    tree = cKDTree(pts)
    try:
        d, _ = tree.query(pts, k=2, workers=-1)
    except TypeError:
        d, _ = tree.query(pts, k=2)
    nn = d[:, 1]
    nn = nn[np.isfinite(nn)]
    nn = nn[nn > 1e-8]
    if len(nn) == 0:
        return 1.0
    return float(np.median(nn))


def generate_superline_components(xyz: np.ndarray, radius: float, min_points: int) -> np.ndarray:
    n = len(xyz)
    frag_ids = np.full(n, -1, dtype=np.int32)
    if n == 0:
        return frag_ids
    tree = cKDTree(xyz)
    visited = np.zeros(n, dtype=bool)
    current_id = 0
    for start in range(n):
        if visited[start]:
            continue
        queue = [start]
        visited[start] = True
        comp = []
        qpos = 0
        while qpos < len(queue):
            u = queue[qpos]
            qpos += 1
            comp.append(u)
            nbrs = tree.query_ball_point(xyz[u], r=radius)
            for v in nbrs:
                if not visited[v]:
                    visited[v] = True
                    queue.append(v)
        if len(comp) >= min_points:
            frag_ids[np.asarray(comp, dtype=np.int64)] = current_id
            current_id += 1
    return frag_ids


def pca_fragment_stats(points: np.ndarray) -> Dict[str, object]:
    n = len(points)
    if n == 0:
        return {
            "centroid": np.zeros(3, dtype=np.float32),
            "tangent": np.array([1, 0, 0], dtype=np.float32),
            "length": 0.0,
            "width": 0.0,
            "linearness": 0.0,
            "eigvals": np.zeros(3, dtype=np.float32),
        }
    centroid = points.mean(axis=0)
    if n < 3:
        tangent = points[-1] - points[0] if n > 1 else np.array([1, 0, 0], dtype=np.float32)
        tangent = tangent / (np.linalg.norm(tangent) + 1e-8)
        proj = (points - centroid) @ tangent
        length = float(np.max(proj) - np.min(proj)) if n > 1 else 0.0
        return {
            "centroid": centroid.astype(np.float32),
            "tangent": tangent.astype(np.float32),
            "length": length,
            "width": 0.0,
            "linearness": 1.0 if n > 1 else 0.0,
            "eigvals": np.zeros(3, dtype=np.float32),
        }
    centered = points - centroid
    cov = np.cov(centered.T)
    vals, vecs = np.linalg.eigh(cov)
    order = np.argsort(vals)[::-1]
    vals = vals[order].astype(np.float32)
    vecs = vecs[:, order].astype(np.float32)
    tangent = vecs[:, 0]
    tangent = tangent / (np.linalg.norm(tangent) + 1e-8)
    proj = centered @ tangent
    length = float(np.max(proj) - np.min(proj))
    recon = np.outer(proj, tangent)
    perp = centered - recon
    width = float(np.sqrt(np.mean(np.sum(perp * perp, axis=1))))
    linearness = float((vals[0] - vals[1]) / (vals[0] + 1e-8)) if vals[0] > 0 else 0.0
    return {
        "centroid": centroid.astype(np.float32),
        "tangent": tangent.astype(np.float32),
        "length": length,
        "width": width,
        "linearness": linearness,
        "eigvals": vals,
    }


