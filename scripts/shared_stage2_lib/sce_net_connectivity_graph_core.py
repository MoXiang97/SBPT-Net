def ensure_dir(path: str | Path) -> None:
    os.makedirs(str(path), exist_ok=True)


def summary_path(output_root: str | Path, subdir: Optional[str], filename: str) -> str:
    """Return a path under summaries/, creating the module subfolder.

    Final V1 primary summary subdirs:
      00_manifest/              run manifest and downsample statistics
      01_token_evidence/        raw local and context-refined token evidence
      02_cluster_refiner/       cluster-aware PT evidence diagnostics
      03_v19_polar_corridor/    final V19.6c polar path/corridor evaluation
      04_seed_retrieval/        seed purity/retrieval diagnostics
      99_best_reference/        read-only previous-best reference copy

    Legacy compatibility directories are written only for small CSVs when needed.
    """
    root = os.path.join(str(output_root), "summaries")
    if subdir:
        root = os.path.join(root, subdir)
    ensure_dir(root)
    return os.path.join(root, filename)


def write_summary_csv(
    df: pd.DataFrame,
    cfg: Config,
    subdir: str,
    filename: str,
    *,
    legacy_subdir: Optional[str] = None,
    legacy_filename: Optional[str] = None,
    index: bool = False,
) -> str:
    """Write a primary summary CSV and optionally a small legacy-compatible copy.

    This helper only manages files. It does not alter any dataframe content.
    """
    primary = summary_path(cfg.output_root, subdir, filename)
    df.to_csv(primary, index=index)
    if legacy_subdir and legacy_filename:
        legacy = summary_path(cfg.output_root, legacy_subdir, legacy_filename)
        if os.path.abspath(primary) != os.path.abspath(legacy):
            df.to_csv(legacy, index=index)
    return primary


def reset_summary_layout(output_root: str | Path, clean: bool = True) -> None:
    """Create a tidy summaries layout.

    When clean=True, removes only output_root/summaries. It does not touch models,
    paper visualizations, caches, or any other experiment outputs.
    """
    root = os.path.join(str(output_root), "summaries")
    if clean and os.path.isdir(root):
        shutil.rmtree(root)
    ensure_dir(root)
    for subdir in [
        "00_manifest",
        "01_token_evidence",
        "02_cluster_refiner",
        "03_v19_polar_corridor",
        "04_seed_retrieval",
        "99_best_reference",
    ]:
        ensure_dir(os.path.join(root, subdir))


