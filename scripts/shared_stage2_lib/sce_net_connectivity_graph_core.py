def _simple_rgb_red_blue(mask: np.ndarray, invalid_mask: Optional[np.ndarray] = None) -> np.ndarray:
    """Red for True, blue for False, gray for invalid."""
    mask = np.asarray(mask).astype(bool)
    rgb = np.zeros((len(mask), 3), dtype=np.uint8)
    rgb[:] = np.array([0, 0, 255], dtype=np.uint8)
    rgb[mask] = np.array([255, 0, 0], dtype=np.uint8)
    if invalid_mask is not None:
        invalid_mask = np.asarray(invalid_mask).astype(bool)
        rgb[invalid_mask] = np.array([130, 130, 130], dtype=np.uint8)
    return rgb


def _simple_fragid_rgb(frag_ids: np.ndarray) -> np.ndarray:
    frag_ids = np.asarray(frag_ids).astype(np.int64)
    rgb = np.zeros((len(frag_ids), 3), dtype=np.uint8)
    for i, fid in enumerate(frag_ids):
        if int(fid) < 0:
            rgb[i] = np.array([130, 130, 130], dtype=np.uint8)
        else:
            f = int(fid)
            rgb[i] = np.array([(37 * f + 67) % 256, (97 * f + 131) % 256, (17 * f + 211) % 256], dtype=np.uint8)
    return rgb


def _simple_error_rgb_label(gt: np.ndarray, pred: np.ndarray):
    """Label: 0=TN blue, 1=TP yellow, 2=FP red, 3=FN green."""
    gt = np.asarray(gt).astype(bool)
    pred = np.asarray(pred).astype(bool)
    err = np.zeros(len(gt), dtype=np.int32)
    err[gt & pred] = 1
    err[(~gt) & pred] = 2
    err[gt & (~pred)] = 3
    rgb = np.zeros((len(gt), 3), dtype=np.uint8)
    rgb[err == 0] = np.array([0, 0, 255], dtype=np.uint8)
    rgb[err == 1] = np.array([255, 220, 0], dtype=np.uint8)
    rgb[err == 2] = np.array([255, 0, 0], dtype=np.uint8)
    rgb[err == 3] = np.array([0, 255, 0], dtype=np.uint8)
    return rgb, err


def _write_xyz_rgb_label(save_path: str, xyz: np.ndarray, rgb: np.ndarray, label: np.ndarray):
    """CloudCompare-friendly minimal file: X Y Z R G B Label."""
    ensure_dir(os.path.dirname(save_path))
    xyz = np.asarray(xyz, dtype=np.float32)
    rgb = np.asarray(rgb)
    if rgb.dtype != np.uint8:
        if rgb.size and np.nanmax(rgb) <= 1.5:
            rgb = rgb * 255.0
        rgb = np.clip(np.round(rgb), 0, 255).astype(np.uint8)
    label = np.asarray(label).astype(np.int32)
    arr = np.column_stack([xyz, rgb, label])
    np.savetxt(save_path, arr, fmt="%.6f %.6f %.6f %d %d %d %d", header="X Y Z R G B Label", comments="")


def export_paper_visualization_pack(record: Dict[str, object], prob: np.ndarray, threshold: float, cfg: Config):
    """Export only the key visualization files.

    Output has only one scalar field named Label.
    This avoids the confusing multi-label CloudCompare imports.
    """
    try:
        candidate, frag_info = build_or_load_fragment_cache(record["path"], record["subset"], cfg)
    except Exception as e:
        print(f"[WARN] paper visualization failed to load fragment cache for {record['sample_id']}: {e}")
        return False

    ds = record["downsampled"]
    prob = np.asarray(prob, dtype=np.float32)
    pred = prob >= float(threshold)
    ds_frag = ds["fragment_id"].astype(np.int64)

    key = f"{record['domain']}_{record['split']}_{record['subset']}"
    prefix = record["sample_id"]
    root = os.path.join(cfg.output_root, PAPER_VIS_OUTPUT_DIRNAME, key)

    # 00: superline before downsampling, FragmentID color.
    cxyz = candidate["xyz"].astype(np.float32)
    cfrag = frag_info["frag_ids"].astype(np.int32)
    cfrag_rgb = _simple_fragid_rgb(cfrag)
    _write_xyz_rgb_label(
        os.path.join(root, "00_fragid", prefix + "_00.txt"),
        cxyz, cfrag_rgb, cfrag
    )

    # 01: superline before downsampling, selected fragments red / unselected blue.
    pred_frag_set = set(int(x) for x in np.unique(ds_frag[pred]))
    frag_pred = np.array([(int(fid) in pred_frag_set) if int(fid) >= 0 else False for fid in cfrag], dtype=bool)
    frag_pred_rgb = _simple_rgb_red_blue(frag_pred, invalid_mask=(cfrag < 0))
    _write_xyz_rgb_label(
        os.path.join(root, "01_pred_rb", prefix + "_01.txt"),
        cxyz, frag_pred_rgb, frag_pred.astype(np.int32)
    )

    if len(ds["xyz"]) == 0:
        return True

    dxyz = ds["xyz"].astype(np.float32)
    dgt = ds["label"].astype(np.int32)
    dpred = pred.astype(np.int32)

    # 02: downsampled GT red/blue.
    dgt_rgb = _simple_rgb_red_blue(dgt.astype(bool))
    _write_xyz_rgb_label(
        os.path.join(root, "02_ds_gt_rb", prefix + "_02.txt"),
        dxyz, dgt_rgb, dgt
    )

    # 03: downsampled prediction red/blue.
    dpred_rgb = _simple_rgb_red_blue(dpred.astype(bool))
    _write_xyz_rgb_label(
        os.path.join(root, "03_ds_pred_rb", prefix + "_03.txt"),
        dxyz, dpred_rgb, dpred
    )

    # 04: downsampled error map. Label: 0=TN, 1=TP, 2=FP, 3=FN.
    err_rgb, err_label = _simple_error_rgb_label(dgt, dpred)
    _write_xyz_rgb_label(
        os.path.join(root, "04_ds_err", prefix + "_04.txt"),
        dxyz, err_rgb, err_label
    )

    return True


