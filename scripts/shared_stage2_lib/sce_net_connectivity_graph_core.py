def _safe_prob_to_logit(prob: np.ndarray) -> np.ndarray:
    p = np.clip(np.asarray(prob, dtype=np.float32), 1e-5, 1.0 - 1e-5)
    return np.log(p / (1.0 - p)).astype(np.float32)


def eval_records_with_prob_key(records: List[Dict[str, object]], threshold: float, cfg: Config, prob_key: str, desc: str = "Evaluate") -> pd.DataFrame:
    """Evaluate records using a chosen probability key, without visualization side effects."""
    rows = []
    for r in tqdm(records, desc=desc):
        ds = r["downsampled"]
        prob = np.asarray(r.get(prob_key, np.zeros(0, dtype=np.float32)), dtype=np.float32)
        y = np.asarray(ds["label"], dtype=np.int64)
        if len(prob) != len(y):
            prob = np.zeros(len(y), dtype=np.float32)
        pred = prob >= float(threshold)
        m = binary_metrics(y, pred)
        rows.append({
            "domain": r["domain"],
            "split": r["split"],
            "subset": r["subset"],
            "sample_id": r["sample_id"],
            "path": r["path"],
            "downsampled_points": int(len(y)),
            "positive_points": int(np.sum(y)),
            "pred_points": int(np.sum(pred)),
            "point_iou": m["iou"],
            "point_f1": m["f1"],
            "point_precision": m["precision"],
            "point_recall": m["recall"],
            "tp": m["tp"],
            "fp": m["fp"],
            "fn": m["fn"],
            "tn": m["tn"],
        })
    return pd.DataFrame(rows)


