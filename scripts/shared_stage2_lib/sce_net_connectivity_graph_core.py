def _copy_and_compare_previous_best(
    cfg: Config,
    contour_agg: pd.DataFrame,
) -> Dict[str, object]:
    """Copy a previous best closed result to summaries/99_best_reference/ and compare with current result.

    This helper is summary-only. It does not modify any model, seed, search,
    threshold, or prediction logic.
    """
    requested_root = str(getattr(cfg, "previous_best_root", ""))
    fallback_roots = [requested_root]
    if requested_root and not requested_root.endswith("_cache_only_recheck"):
        fallback_roots.append(requested_root + "_cache_only_recheck")
    fallback_roots.append(os.path.join(
        BASE_DIR,
        "experiments",
        "E_v19_6c_polar_auto_tune",
        "exp_089_twoend_r12_18_prob15_cache_only_recheck",
    ))

    previous_best_root = ""
    for cand in fallback_roots:
        if cand and os.path.exists(cand):
            previous_best_root = cand
            break
    if not previous_best_root:
        previous_best_root = requested_root

    result = {
        "previous_best_reference_missing": True,
        "previous_best_path": previous_best_root,
        "previous_best_mean_iou": None,
        "previous_best_a_iou": None,
        "previous_best_b_iou": None,
        "previous_best_c_iou": None,
        "previous_best_a_precision": None,
        "previous_best_a_recall": None,
        "previous_best_b_precision": None,
        "previous_best_b_recall": None,
        "previous_best_c_precision": None,
        "previous_best_c_recall": None,
    }

    if not previous_best_root or not os.path.exists(previous_best_root):
        print(f"[PreviousBest] WARNING: Previous best result not found. requested={requested_root}")
        return result

    try:
        ref_dir = Path(cfg.output_root) / "summaries" / "99_best_reference"
        ensure_dir(ref_dir)

        files_to_copy = [
            (["result_summary.txt"], "previous_best_result_summary.txt"),
            ([
                os.path.join("summaries", "03_v19_polar_corridor", "v19_corridor_eval_by_split_subset.csv"),
                os.path.join("summaries", "03_closed_contour", "closed_contour_pt_eval_by_split_subset.csv"),
            ], "previous_best_v19_corridor_eval_by_split_subset.csv"),
            ([
                os.path.join("summaries", "03_v19_polar_corridor", "v19_polar_geometry_by_split_subset.csv"),
                os.path.join("summaries", "03_closed_contour", "closed_contour_geometry_by_split_subset.csv"),
            ], "previous_best_v19_polar_geometry_by_split_subset.csv"),
        ]

        for src_rel_candidates, dst_name in files_to_copy:
            src = ""
            for src_rel in src_rel_candidates:
                cand_src = os.path.join(previous_best_root, src_rel)
                if os.path.exists(cand_src):
                    src = cand_src
                    break
            dst = os.path.join(str(ref_dir), dst_name)
            if src:
                # Avoid copying a file onto itself when the current output folder
                # is also used as the reference folder.
                if os.path.abspath(src) != os.path.abspath(dst):
                    shutil.copyfile(src, dst)
                print(f"[PreviousBest] Reference file available: {src}")

        prev_eval_candidates = [
            os.path.join(previous_best_root, "summaries", "03_v19_polar_corridor", "v19_corridor_eval_by_split_subset.csv"),
            os.path.join(previous_best_root, "summaries", "03_closed_contour", "closed_contour_pt_eval_by_split_subset.csv"),
        ]
        prev_eval_path = next((x for x in prev_eval_candidates if os.path.exists(x)), "")
        if prev_eval_path:
            prev_eval = pd.read_csv(prev_eval_path)
            for subset in ["shoe_a", "shoe_b", "shoe_c"]:
                mask = (prev_eval["domain"] == "real") & (prev_eval["split"] == "test") & (prev_eval["subset"] == subset)
                if not mask.any():
                    continue
                row = prev_eval[mask].iloc[0]
                key = subset.replace("shoe_", "")
                result[f"previous_best_{key}_iou"] = float(row.get("micro_point_iou", np.nan))
                result[f"previous_best_{key}_precision"] = float(row.get("micro_point_precision", np.nan))
                result[f"previous_best_{key}_recall"] = float(row.get("micro_point_recall", np.nan))

            ious = [result["previous_best_a_iou"], result["previous_best_b_iou"], result["previous_best_c_iou"]]
            valid_ious = [iou for iou in ious if iou is not None and np.isfinite(iou)]
            if valid_ious:
                result["previous_best_mean_iou"] = sum(valid_ious) / len(valid_ious)
            result["previous_best_reference_missing"] = False

    except Exception as e:
        print(f"[PreviousBest] WARNING: Failed to process previous best result: {e}")

    return result


