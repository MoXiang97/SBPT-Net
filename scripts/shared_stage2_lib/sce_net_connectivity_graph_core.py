def config_to_dict_v14(cfg: Config) -> Dict[str, object]:
    """Dataclass Config plus dynamically attached V15 fields.

    NOTE: The first V15 draft accidentally called config_to_dict_v14(cfg)
    inside this function, which caused infinite recursion right after raw MLP
    training when saving checkpoints/config.  This version starts from
    dataclasses.asdict(cfg) and then adds any runtime-attached fields safely.
    """
    def _jsonable(v):
        if isinstance(v, (str, int, float, bool)) or v is None:
            return v
        if isinstance(v, Path):
            return str(v)
        if isinstance(v, (list, tuple)):
            return [_jsonable(x) for x in v]
        if isinstance(v, dict):
            return {str(k): _jsonable(x) for k, x in v.items()}
        try:
            if isinstance(v, np.generic):
                return v.item()
            if isinstance(v, np.ndarray):
                return v.tolist()
        except Exception:
            pass
        try:
            json.dumps(v)
            return v
        except TypeError:
            return str(v)

    try:
        base = asdict(cfg)
    except Exception:
        base = {}
    d: Dict[str, object] = {str(k): _jsonable(v) for k, v in base.items()}
    for k, v in vars(cfg).items():
        d[str(k)] = _jsonable(v)
    return d


def robust_center_normalize_3d_v15(xyz: np.ndarray, base_spacing: float) -> Tuple[np.ndarray, np.ndarray]:
    """Return file-local 3D coordinates normalized by base_spacing.

    No PCA projection is used.  The contour head works directly in 3D token XYZ.
    Coordinates are only translated by the per-file median and scaled by base_spacing
    for numerical stability; all contour distances are true 3D segment distances.
    """
    xyz = np.asarray(xyz, dtype=np.float64)
    if len(xyz) == 0:
        return np.zeros((0, 3), dtype=np.float64), np.zeros(3, dtype=np.float64)
    center3 = np.median(xyz, axis=0).astype(np.float64)
    scale = max(float(base_spacing), 1e-6)
    xyz_norm = (xyz - center3[None, :]) / scale
    return xyz_norm.astype(np.float64), center3.astype(np.float64)

def estimate_base_spacing_from_ds_v14(ds: Dict[str, np.ndarray]) -> float:
    """Use the same downsample feature column when available; fall back to NN spacing."""
    try:
        if "features" in ds and "base_spacing" in DOWNSAMPLED_FEATURE_NAMES:
            j = DOWNSAMPLED_FEATURE_NAMES.index("base_spacing")
            vals = np.asarray(ds["features"], dtype=np.float32)[:, j]
            vals = vals[np.isfinite(vals) & (vals > 0)]
            if len(vals):
                return float(np.median(vals))
    except Exception:
        pass
    for key in ["base_spacing", "candidate_base_spacing"]:
        if key in ds:
            try:
                val = float(np.asarray(ds[key]).reshape(-1)[0])
                if np.isfinite(val) and val > 0:
                    return val
            except Exception:
                pass
    xyz = np.asarray(ds.get("xyz", np.zeros((0, 3), dtype=np.float32)), dtype=np.float32)
    if len(xyz) >= 2:
        try:
            return max(float(estimate_base_spacing(xyz)), 1e-6)
        except Exception:
            pass
    return 1.0


