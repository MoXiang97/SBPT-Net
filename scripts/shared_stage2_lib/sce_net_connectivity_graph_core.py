def batched_predict_patch_attribute_concat_prob(model, patch_points: np.ndarray, patch_mask: np.ndarray, feat_x: np.ndarray, cfg: Config) -> np.ndarray:
    """Batched inference for the local-patch and token-attribute classifier."""
    if len(patch_points) == 0:
        return np.zeros(0, dtype=np.float32)
    device = torch.device(cfg.device)
    model.eval()
    probs = []
    step = max(1, cfg.infer_batch_size)
    tta_passes = max(1, int(getattr(cfg, "raw_patch_tta_passes", 1)))
    with torch.no_grad():
        for start in range(0, len(patch_points), step):
            end = start + step
            pb = torch.from_numpy(patch_points[start:end].astype(np.float32)).to(device)
            mb = torch.from_numpy(patch_mask[start:end].astype(np.float32)).to(device)
            xb = torch.from_numpy(feat_x[start:end].astype(np.float32)).to(device)
            prob_sum = torch.sigmoid(model(pb, mb, xb))
            # Diagnostic TTA path only. With the default tta_passes=1 this block
            # is skipped, so inference is a single deterministic forward pass.
            if tta_passes > 1:
                old_mode = getattr(cfg, "raw_patch_aug_mode", "none")
                old_dropout = float(getattr(cfg, "raw_patch_dropout", 0.0))
                old_jitter = float(getattr(cfg, "raw_patch_jitter_std", 0.0))
                old_scale = float(getattr(cfg, "raw_patch_scale_jitter", 0.0))
                cfg.raw_patch_aug_mode = "scan_noise"
                cfg.raw_patch_dropout = float(getattr(cfg, "raw_patch_tta_dropout", 0.0))
                cfg.raw_patch_jitter_std = float(getattr(cfg, "raw_patch_tta_jitter_std", 0.0))
                cfg.raw_patch_scale_jitter = float(getattr(cfg, "raw_patch_tta_scale_jitter", 0.0))
                try:
                    for _ in range(tta_passes - 1):
                        pb_aug, mb_aug = augment_patch_points_for_domain_randomization(pb, mb, cfg)
                        prob_sum = prob_sum + torch.sigmoid(model(pb_aug, mb_aug, xb))
                finally:
                    cfg.raw_patch_aug_mode = old_mode
                    cfg.raw_patch_dropout = old_dropout
                    cfg.raw_patch_jitter_std = old_jitter
                    cfg.raw_patch_scale_jitter = old_scale
            p = (prob_sum / float(tta_passes)).detach().cpu().numpy()
            probs.append(p)
    return np.concatenate(probs, axis=0).astype(np.float32)


def choose_threshold_from_val(val_probs: np.ndarray, val_y: np.ndarray, cfg: Config) -> float:
    """Select threshold by synthetic-val point IoU on the fixed 0.05..0.95 grid."""
    if len(val_y) == 0:
        return float(DEFAULT_THRESHOLD)
    rows = []
    for t in THRESHOLD_GRID:
        m = binary_metrics(val_y, val_probs >= float(t))
        rows.append({"threshold": float(t), **m})
    df = pd.DataFrame(rows)
    best = df.sort_values(["iou", "f1", "threshold"], ascending=[False, False, True]).iloc[0]
    return float(best["threshold"])


def soft_dice_loss_from_logits(logits: torch.Tensor, y: torch.Tensor, eps: float = 1e-6) -> torch.Tensor:
    prob = torch.sigmoid(logits)
    y = y.float()
    inter = torch.sum(prob * y)
    den = torch.sum(prob) + torch.sum(y)
    return 1.0 - (2.0 * inter + eps) / (den + eps)


def lovasz_hinge_loss_from_logits(logits: torch.Tensor, y: torch.Tensor) -> torch.Tensor:
    """Binary Lovasz hinge loss, a convex surrogate for optimizing IoU."""
    if logits.numel() == 0:
        return logits.sum() * 0.0
    labels = y.float()
    signs = 2.0 * labels - 1.0
    errors = 1.0 - logits * signs
    errors_sorted, perm = torch.sort(errors, dim=0, descending=True)
    labels_sorted = labels[perm]
    total_pos = torch.sum(labels_sorted)
    if total_pos <= 0:
        return torch.relu(errors_sorted).mean()
    intersection = total_pos - torch.cumsum(labels_sorted, dim=0)
    union = total_pos + torch.cumsum(1.0 - labels_sorted, dim=0)
    jaccard = 1.0 - intersection / torch.clamp(union, min=1e-6)
    if jaccard.numel() > 1:
        jaccard = torch.cat([jaccard[:1], jaccard[1:] - jaccard[:-1]], dim=0)
    return torch.dot(torch.relu(errors_sorted), jaccard)


def tversky_loss_from_logits(logits: torch.Tensor, y: torch.Tensor, alpha: float = 0.70) -> torch.Tensor:
    """Soft Tversky loss; alpha emphasizes false-positive cost."""
    if logits.numel() == 0:
        return logits.sum() * 0.0
    p = torch.sigmoid(logits)
    y = y.float()
    alpha_t = float(np.clip(alpha, 0.05, 0.95))
    beta_t = 1.0 - alpha_t
    tp = torch.sum(p * y)
    fp = torch.sum(p * (1.0 - y))
    fn = torch.sum((1.0 - p) * y)
    score = (tp + 1.0) / (tp + alpha_t * fp + beta_t * fn + 1.0)
    return 1.0 - score



