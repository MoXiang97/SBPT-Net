def apply_feature_ablation_to_records(records: List[Dict[str, object]], cfg: Config) -> None:
    """Apply training-time feature/evidence ablations without changing cache files."""
    mode = str(getattr(cfg, "ablation_feature_mode", "full") or "full").lower()
    if mode in ("", "full", "none"):
        return

    parent_idx = [
        DOWNSAMPLED_FEATURE_NAMES.index(name)
        for name in PARENT_SUPERLINE_FEATURE_NAMES
        if name in DOWNSAMPLED_FEATURE_NAMES
    ]
    for r in records:
        ds = r.get("downsampled", {})
        n = int(len(ds.get("label", [])))
        if mode in ("patch_only", "k64_patch_only"):
            feat = np.asarray(ds.get("features", np.zeros((n, len(DOWNSAMPLED_FEATURE_NAMES)), dtype=np.float32)), dtype=np.float32)
            ds["features"] = np.zeros_like(feat, dtype=np.float32)
        elif mode in ("features_only", "no_k64_patch"):
            pp = np.asarray(ds.get("patch_points", np.zeros((n, int(cfg.patch_point_count), int(cfg.patch_point_dim)), dtype=np.float32)), dtype=np.float32)
            pm = np.asarray(ds.get("patch_mask", np.zeros((n, int(cfg.patch_point_count)), dtype=np.float32)), dtype=np.float32)
            ds["patch_points"] = np.zeros_like(pp, dtype=np.float32)
            ds["patch_mask"] = np.zeros_like(pm, dtype=np.float32)
        elif mode in ("no_parent_superline", "zero_parent_superline"):
            feat = np.asarray(ds.get("features", np.zeros((n, len(DOWNSAMPLED_FEATURE_NAMES)), dtype=np.float32)), dtype=np.float32).copy()
            if feat.ndim == 2 and feat.shape[1] >= len(DOWNSAMPLED_FEATURE_NAMES):
                feat[:, parent_idx] = 0.0
            ds["features"] = feat
        else:
            raise ValueError(f"Unknown ablation_feature_mode: {mode}")


def _local_width(points: np.ndarray, center: np.ndarray, tangent: np.ndarray, q: float) -> float:
    if len(points) <= 1:
        return 0.0
    tangent = tangent / (np.linalg.norm(tangent) + 1e-8)
    rel = points - center[None, :]
    u = rel @ tangent
    perp = rel - np.outer(u, tangent)
    d = np.linalg.norm(perp, axis=1)
    return float(np.quantile(d, q)) if len(d) else 0.0


def _source_anchored_medoid(
    pts: np.ndarray,
    orig: np.ndarray,
    target: Optional[np.ndarray] = None,
) -> Tuple[np.ndarray, int, int, float]:
    """Return an actual input point closest to target/centroid.

    v12 safety rule:
    - PCA may estimate local directions, but it must not create new geometry.
    - The final representative XYZ is always one of the original candidate points
      inside the current group.
    """
    pts = np.asarray(pts, dtype=np.float32)
    orig = np.asarray(orig, dtype=np.int64)
    if len(pts) == 0:
        return np.zeros(3, dtype=np.float32), -1, -1, 0.0
    if target is None:
        target = np.mean(pts, axis=0).astype(np.float32)
    else:
        target = np.asarray(target, dtype=np.float32)
    d = np.linalg.norm(pts - target[None, :], axis=1)
    j = int(np.argmin(d))
    return pts[j].astype(np.float32), int(orig[j]), j, float(d[j])


def _source_anchored_axis_medoid(
    pts: np.ndarray,
    orig: np.ndarray,
    target: Optional[np.ndarray],
    tangent: Optional[np.ndarray],
    center_weight: float = 0.35,
    perp_weight: float = 1.0,
) -> Tuple[np.ndarray, int, int, float]:
    """Choose a source point close to both the local center and local axis.

    This keeps the output representative point anchored to the original point cloud,
    while reducing side-to-side jitter in wide local patches. PCA only supplies the
    local tangent used in the score; the returned XYZ is always pts[j].
    """
    pts = np.asarray(pts, dtype=np.float32)
    orig = np.asarray(orig, dtype=np.int64)
    if len(pts) == 0:
        return np.zeros(3, dtype=np.float32), -1, -1, 0.0
    if target is None:
        target = np.mean(pts, axis=0).astype(np.float32)
    else:
        target = np.asarray(target, dtype=np.float32)
    if tangent is None:
        return _source_anchored_medoid(pts, orig, target)
    tangent = np.asarray(tangent, dtype=np.float32)
    tn = float(np.linalg.norm(tangent))
    if not np.isfinite(tn) or tn < 1e-8:
        return _source_anchored_medoid(pts, orig, target)
    tangent = tangent / (tn + 1e-8)
    rel = pts - target[None, :]
    u = rel @ tangent
    perp = rel - np.outer(u, tangent)
    center_dist = np.linalg.norm(rel, axis=1)
    perp_dist = np.linalg.norm(perp, axis=1)
    score = float(center_weight) * center_dist + float(perp_weight) * perp_dist
    j = int(np.argmin(score))
    return pts[j].astype(np.float32), int(orig[j]), j, float(center_dist[j])


def _principal_axis(points: np.ndarray, fallback: Optional[np.ndarray] = None) -> np.ndarray:
    pts = np.asarray(points, dtype=np.float32)
    if len(pts) >= 3:
        st = pca_fragment_stats(pts)
        axis = np.asarray(st["tangent"], dtype=np.float32)
    elif len(pts) >= 2:
        axis = (pts[-1] - pts[0]).astype(np.float32)
    elif fallback is not None:
        axis = np.asarray(fallback, dtype=np.float32)
    else:
        axis = np.array([1.0, 0.0, 0.0], dtype=np.float32)
    n = float(np.linalg.norm(axis))
    if not np.isfinite(n) or n < 1e-8:
        if fallback is not None:
            axis = np.asarray(fallback, dtype=np.float32)
            n = float(np.linalg.norm(axis))
    if not np.isfinite(n) or n < 1e-8:
        axis = np.array([1.0, 0.0, 0.0], dtype=np.float32)
        n = 1.0
    return (axis / (n + 1e-8)).astype(np.float32)


def _fixed_patch_relative_points(
    pts: np.ndarray,
    rep_xyz: np.ndarray,
    base_spacing: float,
    max_points: int,
) -> Tuple[np.ndarray, np.ndarray]:
    """Return a fixed-size local patch point set for the Patch PointNet encoder.

    The representation is intentionally domain-light:
    - relative XYZ only: point_xyz - representative_xyz
    - normalized by base_spacing
    - no RGB, no LCC, no absolute XYZ
    - deterministic nearest-to-representative sampling, zero padding, mask
    """
    k = max(1, int(max_points))
    pts = np.asarray(pts, dtype=np.float32)
    rep_xyz = np.asarray(rep_xyz, dtype=np.float32)
    out = np.zeros((k, 3), dtype=np.float32)
    mask = np.zeros((k,), dtype=np.float32)
    if len(pts) == 0:
        return out, mask
    bs = max(float(base_spacing), 1e-6)
    rel = (pts - rep_xyz[None, :]).astype(np.float32) / bs
    d = np.linalg.norm(rel, axis=1)
    # Stable deterministic order: nearest first, with coordinate tie-breakers.
    order = np.lexsort((rel[:, 2], rel[:, 1], rel[:, 0], d))
    sel = order[:min(k, len(order))]
    out[:len(sel)] = rel[sel]
    mask[:len(sel)] = 1.0
    return out, mask


def _fixed_patch_relative_xyzrgb(
    pts: np.ndarray,
    rgb: np.ndarray,
    rep_xyz: np.ndarray,
    base_spacing: float,
    max_points: int,
) -> Tuple[np.ndarray, np.ndarray]:
    """Return the same deterministic patch sample with XYZ and pointwise RGB.

    XYZ is relative to the representative point and normalized by base spacing.
    RGB is normalized to [0, 1]. The point order and padding mask are identical
    to the canonical XYZ-only patch construction.
    """
    k = max(1, int(max_points))
    pts = np.asarray(pts, dtype=np.float32)
    rgb = normalize_rgb(np.asarray(rgb, dtype=np.float32))
    rep_xyz = np.asarray(rep_xyz, dtype=np.float32)
    out = np.zeros((k, 6), dtype=np.float32)
    mask = np.zeros((k,), dtype=np.float32)
    if len(pts) == 0:
        return out, mask
    if rgb.shape != (len(pts), 3):
        raise ValueError(
            f"Pointwise RGB must have shape {(len(pts), 3)}, got {rgb.shape}"
        )
    bs = max(float(base_spacing), 1e-6)
    rel = (pts - rep_xyz[None, :]).astype(np.float32) / bs
    d = np.linalg.norm(rel, axis=1)
    order = np.lexsort((rel[:, 2], rel[:, 1], rel[:, 0], d))
    sel = order[:min(k, len(order))]
    out[:len(sel), :3] = rel[sel]
    out[:len(sel), 3:] = rgb[sel]
    mask[:len(sel)] = 1.0
    return out, mask


def _fixed_patch_model_inputs(
    pts: np.ndarray,
    rgb: np.ndarray,
    rep_xyz: np.ndarray,
    base_spacing: float,
    cfg: Config,
) -> Tuple[np.ndarray, np.ndarray]:
    point_dim = int(cfg.patch_point_dim)
    if point_dim == 3:
        return _fixed_patch_relative_points(
            pts,
            rep_xyz,
            base_spacing,
            int(cfg.patch_point_count),
        )
    if point_dim == 6:
        return _fixed_patch_relative_xyzrgb(
            pts,
            rgb,
            rep_xyz,
            base_spacing,
            int(cfg.patch_point_count),
        )
    raise ValueError(f"Unsupported patch_point_dim={point_dim}; expected 3 or 6")


def _local_patch_indices(
    pts: np.ndarray,
    orig_local_order: np.ndarray,
    radius: float,
    stride: float,
    min_points: int,
) -> List[np.ndarray]:
    """Deterministic local sliding/covering patches for all fragments.

    radius controls the support used to estimate local direction/statistics.
    stride controls seed spacing and therefore axial density. Unlike the earlier
    cover, we do NOT mark the whole support patch as consumed; only a small stride
    neighborhood is suppressed. This keeps representatives denser along the line
    while still using a stable local support for PCA.
    """
    n = len(pts)
    if n == 0:
        return []
    if n <= max(1, int(min_points)):
        return [np.arange(n, dtype=np.int64)]

    tree = cKDTree(pts)
    suppressed = np.zeros(n, dtype=bool)
    seed_order = np.argsort(orig_local_order, kind="mergesort")
    patches: List[np.ndarray] = []
    radius = max(float(radius), 1e-8)
    stride = max(float(stride), 1e-8)
    for seed in seed_order:
        seed = int(seed)
        if suppressed[seed]:
            continue
        neigh = np.asarray(tree.query_ball_point(pts[seed], r=radius), dtype=np.int64)
        if len(neigh) == 0:
            neigh = np.asarray([seed], dtype=np.int64)
        patches.append(np.sort(neigh).astype(np.int64))

        # Suppress only nearby future seeds, not the whole support patch.
        close = np.asarray(tree.query_ball_point(pts[seed], r=stride), dtype=np.int64)
        suppressed[close] = True
    return patches


