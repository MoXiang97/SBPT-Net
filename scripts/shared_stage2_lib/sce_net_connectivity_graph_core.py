def normalize_rgb(rgb: np.ndarray) -> np.ndarray:
    rgb = rgb.astype(np.float32).copy()
    if rgb.size == 0:
        return rgb
    if np.nanmax(rgb) > 1.5:
        rgb /= 255.0
    return np.clip(rgb, 0.0, 1.0)



