def deterministic_fixed_train_val(files: Sequence[str], train_n: int, val_n: int, seed: int) -> Tuple[List[str], List[str]]:
    """Select a fixed number of synthetic train/val files with no overlap.

    This is the E3.1 protocol:
        synthetic train = 500 by default
        synthetic val   = 100 by default

    If the available file count is smaller than train_n + val_n, the function
    keeps the requested ratio as much as possible without replacement.
    """
    files = sorted(files)
    if not files:
        return [], []
    rng = random.Random(seed)
    shuffled = list(files)
    rng.shuffle(shuffled)

    total_requested = max(0, int(train_n)) + max(0, int(val_n))
    total = min(len(shuffled), max(total_requested, 2))
    train_n_eff = min(max(0, int(train_n)), total)
    val_n_eff = min(max(0, int(val_n)), total - train_n_eff)

    # If train request consumed all available files but val was requested, reserve
    # a small validation set whenever possible.
    if val_n > 0 and val_n_eff == 0 and total >= 2:
        val_n_eff = min(max(1, int(round(total * 0.15))), total - 1)
        train_n_eff = total - val_n_eff

    train_files = sorted(shuffled[:train_n_eff])
    val_files = sorted(shuffled[train_n_eff:train_n_eff + val_n_eff])
    return train_files, val_files


def synthetic_style_id(path: str | Path) -> str:
    stem = Path(path).stem
    m = re.match(r"^design_\d+_([^-_]+)-\d+", stem)
    if m:
        return m.group(1)
    base = stem.split("_fused", 1)[0]
    return base.split("-", 1)[0]


def style_holdout_train_val(
    files: Sequence[str],
    train_n: int,
    val_n: int,
    seed: int,
    holdout_styles: Sequence[str],
) -> Tuple[List[str], List[str]]:
    files = sorted(files)
    holdout = {str(s).strip().lower() for s in holdout_styles if str(s).strip()}
    if not files or not holdout:
        return deterministic_fixed_train_val(files, train_n, val_n, seed)

    val_pool = [f for f in files if synthetic_style_id(f).lower() in holdout]
    train_pool = [f for f in files if synthetic_style_id(f).lower() not in holdout]
    if len(train_pool) < int(train_n) or len(val_pool) < int(val_n):
        raise RuntimeError(
            "Style-heldout synthetic split does not have enough files: "
            f"train_pool={len(train_pool)} val_pool={len(val_pool)} requested={train_n}/{val_n} "
            f"holdout_styles={sorted(holdout)}"
        )

    rng = random.Random(seed)
    rng.shuffle(train_pool)
    rng.shuffle(val_pool)
    return sorted(train_pool[: int(train_n)]), sorted(val_pool[: int(val_n)])


def split_synthetic_train_val(files: Sequence[str], cfg: Config) -> Tuple[List[str], List[str]]:
    policy = str(getattr(cfg, "synthetic_split_policy", "random")).strip().lower()
    holdout_styles = [
        s.strip()
        for s in str(getattr(cfg, "synthetic_holdout_styles", "")).split(",")
        if s.strip()
    ]
    if policy in {"style_holdout", "style-heldout", "holdout"}:
        return style_holdout_train_val(
            files,
            int(cfg.max_sim_train),
            int(cfg.max_sim_val),
            int(cfg.split_seed),
            holdout_styles,
        )
    return deterministic_fixed_train_val(
        files,
        int(cfg.max_sim_train),
        int(cfg.max_sim_val),
        int(cfg.split_seed),
    )


