def encode_token_transformer_hidden_and_prob(
    model: nn.Module,
    graph: Dict[str, np.ndarray],
    device: torch.device,
) -> Tuple[np.ndarray, np.ndarray]:
    """Return frozen PT hidden embeddings and refined token probabilities for one file."""
    if graph["x"].shape[0] == 0:
        hidden_dim = int(getattr(model, "input_proj")[0].out_features) if hasattr(model, "input_proj") else 0
        return np.zeros((0, hidden_dim), dtype=np.float16), np.zeros((0,), dtype=np.float32)
    model.eval()
    with torch.no_grad():
        x = torch.from_numpy(graph["x"].astype(np.float32)).to(device)
        nbr_idx = torch.from_numpy(graph["nbr_idx"].astype(np.int64)).to(device)
        nbr_mask = torch.from_numpy(graph["nbr_mask"].astype(bool)).to(device)
        h = model.input_proj(x)
        for layer in model.layers:
            h = layer(h, nbr_idx, nbr_mask)
        delta = model.delta_head(h).squeeze(1)
        raw_logit = x[:, len(DOWNSAMPLED_FEATURE_NAMES)]
        prob = torch.sigmoid(raw_logit + delta)
    return h.detach().cpu().numpy().astype(np.float16), prob.detach().cpu().numpy().astype(np.float32)


def prepare_closed_contour_records(
    records: List[Dict[str, object]],
    token_transformer_model: nn.Module,
    feat_mean: np.ndarray,
    feat_std: np.ndarray,
    cfg: Config,
) -> None:
    """Attach frozen PT hidden/evidence and normalized 3D coordinates to each record.

    IMPORTANT: no global PCA/2D projection is used. The closed contour head receives
    3D token coordinates centered by median XYZ and normalized by base_spacing.
    """
    device = torch.device(cfg.device)
    for r in tqdm(records, desc="Prepare PT hidden + 3D coordinates for contour head"):
        ds = r["downsampled"]
        n = int(len(ds.get("label", [])))
        if n == 0:
            r["pt_hidden"] = np.zeros((0, int(getattr(cfg, "token_transformer_hidden_dim", 96))), dtype=np.float16)
            r["pt_evidence_prob"] = np.zeros((0,), dtype=np.float32)
            r["xyz3d_norm"] = np.zeros((0, 3), dtype=np.float32)
            r["base_spacing"] = 1.0
            r["xyz_center3"] = np.zeros(3, dtype=np.float32)
            continue
        graph = build_superline_transformer_input(r, feat_mean, feat_std, cfg, prob_key="prob")
        hidden, prob = encode_token_transformer_hidden_and_prob(token_transformer_model, graph, device)
        # V19.1-cluster-aware: keep Token Transformer hidden for geometry modules,
        # but let downstream PT-guided ring/contour evidence optionally use the
        # cluster-aware refined probability.  This is only an evidence replacement;
        # it does not add path search, region growing, or any new contour training.
        evidence_key = str(getattr(cfg, "contour_evidence_prob_key", "token_transformer_prob"))
        if evidence_key != "token_transformer_prob":
            alt_prob = np.asarray(r.get(evidence_key, np.zeros(n, dtype=np.float32)), dtype=np.float32)
            if len(alt_prob) == n:
                prob = alt_prob
        xyz = np.asarray(ds.get("xyz", np.zeros((n, 3), dtype=np.float32)), dtype=np.float32)
        base_spacing = estimate_base_spacing_from_ds_v14(ds)
        xyz_norm, center3 = robust_center_normalize_3d_v15(xyz, base_spacing)
        r["pt_hidden"] = hidden
        r["pt_evidence_prob"] = prob
        r["xyz3d_norm"] = xyz_norm.astype(np.float32)
        r["base_spacing"] = float(base_spacing)
        r["xyz_center3"] = center3.astype(np.float32)


def prepare_closed_contour_records_without_transformer(records: List[Dict[str, object]], cfg: Config) -> None:
    """Prepare V19 coordinates when an ablation bypasses the Token Transformer."""
    evidence_key = str(getattr(cfg, "contour_evidence_prob_key", "prob"))
    for r in tqdm(records, desc="Prepare raw evidence + 3D coordinates for contour head"):
        ds = r["downsampled"]
        n = int(len(ds.get("label", [])))
        r["pt_hidden"] = np.zeros((n, int(getattr(cfg, "token_transformer_hidden_dim", 96))), dtype=np.float16)
        prob = np.asarray(r.get(evidence_key, r.get("prob", np.zeros(n, dtype=np.float32))), dtype=np.float32)
        if len(prob) != n:
            prob = np.zeros(n, dtype=np.float32)
        xyz = np.asarray(ds.get("xyz", np.zeros((n, 3), dtype=np.float32)), dtype=np.float32)
        base_spacing = estimate_base_spacing_from_ds_v14(ds) if n > 0 else 1.0
        xyz_norm, center3 = robust_center_normalize_3d_v15(xyz, base_spacing) if n > 0 else (np.zeros((0, 3), dtype=np.float32), np.zeros(3, dtype=np.float32))
        r["pt_evidence_prob"] = prob.astype(np.float32)
        r["xyz3d_norm"] = xyz_norm.astype(np.float32)
        r["base_spacing"] = float(base_spacing)
        r["xyz_center3"] = center3.astype(np.float32)

