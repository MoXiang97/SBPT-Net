def aggregate_eval(df: pd.DataFrame) -> pd.DataFrame:
    if df.empty:
        return df
    agg = df.groupby(["domain", "split", "subset"]).agg(
        files=("sample_id", "count"),
        mean_downsampled_points=("downsampled_points", "mean"),
        mean_positive_points=("positive_points", "mean"),
        mean_pred_points=("pred_points", "mean"),
        mean_point_iou=("point_iou", "mean"),
        mean_point_f1=("point_f1", "mean"),
        mean_point_precision=("point_precision", "mean"),
        mean_point_recall=("point_recall", "mean"),
        total_tp=("tp", "sum"),
        total_fp=("fp", "sum"),
        total_fn=("fn", "sum"),
        total_tn=("tn", "sum"),
    ).reset_index()

    agg["micro_point_iou"] = agg["total_tp"] / (agg["total_tp"] + agg["total_fp"] + agg["total_fn"]).replace(0, np.nan)
    agg["micro_point_precision"] = agg["total_tp"] / (agg["total_tp"] + agg["total_fp"]).replace(0, np.nan)
    agg["micro_point_recall"] = agg["total_tp"] / (agg["total_tp"] + agg["total_fn"]).replace(0, np.nan)
    agg["micro_point_f1"] = (
        2 * agg["micro_point_precision"] * agg["micro_point_recall"]
        / (agg["micro_point_precision"] + agg["micro_point_recall"]).replace(0, np.nan)
    )
    return agg


def _summary_table(df: Optional[pd.DataFrame], cols: Optional[List[str]] = None) -> str:
    if df is None or df.empty:
        return "(empty)"
    out = df[[c for c in cols if c in df.columns]] if cols else df
    return out.to_string(index=False, float_format=lambda x: f"{x:.6f}")


