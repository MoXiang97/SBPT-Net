def build_same_fragment_window_indices(record: Dict[str, object], order_window: int) -> Tuple[np.ndarray, np.ndarray]:
    """Build local attention windows using only superline/fragment structure.

    This intentionally avoids radius/kNN neighbors in the first version, because
    spatially nearby shoe-upper texture/interference lines can be semantically
    unrelated to the true processing boundary.

    For each token, neighbors are tokens from the same fragment whose ordered
    position is within +/- order_window. Padding positions point to self and are
    masked out.
    """
    ds = record["downsampled"]
    y = np.asarray(ds.get("label", []))
    n = int(len(y))
    w = int(max(0, order_window))
    width = 2 * w + 1
    if n == 0:
        return np.zeros((0, width), dtype=np.int64), np.zeros((0, width), dtype=bool)

    nbr_idx = np.tile(np.arange(n, dtype=np.int64).reshape(-1, 1), (1, width))
    nbr_mask = np.zeros((n, width), dtype=bool)

    frag = np.asarray(ds.get("fragment_id", np.full(n, -1, dtype=np.int32)), dtype=np.int64)
    orig = np.asarray(ds.get("orig_index", np.arange(n, dtype=np.int64)), dtype=np.int64)
    feat_raw = np.asarray(ds.get("features", np.zeros((n, len(DOWNSAMPLED_FEATURE_NAMES)), dtype=np.float32)), dtype=np.float32)
    if feat_raw.ndim == 2 and feat_raw.shape[1] > DOWNSAMPLED_FEATURE_NAMES.index("token_order_norm"):
        token_order = feat_raw[:, DOWNSAMPLED_FEATURE_NAMES.index("token_order_norm")]
    else:
        token_order = np.arange(n, dtype=np.float32)

    for fid in np.unique(frag):
        idx = np.where(frag == fid)[0]
        if len(idx) == 0:
            continue
        local_order = np.lexsort((orig[idx], token_order[idx]))
        ordered = idx[local_order]
        L = len(ordered)
        for pos, center_idx in enumerate(ordered):
            lo = max(0, pos - w)
            hi = min(L, pos + w + 1)
            local_neighbors = ordered[lo:hi]
            k = len(local_neighbors)
            nbr_idx[int(center_idx), :k] = local_neighbors.astype(np.int64)
            nbr_mask[int(center_idx), :k] = True
    return nbr_idx.astype(np.int64), nbr_mask.astype(bool)


def build_spatial_knn_window_indices(record: Dict[str, object], cfg: Config) -> Tuple[np.ndarray, np.ndarray]:
    """Build a small geometry-local context window for optional local-global fusion.

    The same-fragment window captures long line continuity. This optional window
    gives the evidence refiner a conservative local neighborhood for weak or
    broken line evidence, without introducing a cluster/path/search heuristic.
    """
    ds = record["downsampled"]
    y = np.asarray(ds.get("label", []))
    n = int(len(y))
    k = max(1, int(getattr(cfg, "token_transformer_spatial_k", 12)))
    width = k + 1
    if n == 0:
        return np.zeros((0, width), dtype=np.int64), np.zeros((0, width), dtype=bool)

    nbr_idx = np.tile(np.arange(n, dtype=np.int64).reshape(-1, 1), (1, width))
    nbr_mask = np.zeros((n, width), dtype=bool)
    xyz = np.asarray(ds.get("xyz", np.zeros((n, 3), dtype=np.float32)), dtype=np.float32)
    if len(xyz) != n or n == 1:
        nbr_mask[:, 0] = True
        return nbr_idx.astype(np.int64), nbr_mask.astype(bool)

    base_spacing = _base_spacing_from_downsampled(ds)
    radius = max(float(getattr(cfg, "token_transformer_spatial_radius_factor", 8.0)) * max(base_spacing, 1e-6), 1e-6)
    tree = cKDTree(xyz)
    kk = min(width, n)
    dist, ind = tree.query(xyz, k=kk)
    if kk == 1:
        dist = dist.reshape(-1, 1)
        ind = ind.reshape(-1, 1)
    for i in range(n):
        local_ind = np.asarray(ind[i], dtype=np.int64).reshape(-1)
        local_dist = np.asarray(dist[i], dtype=np.float32).reshape(-1)
        keep = np.isfinite(local_dist) & (local_dist <= radius)
        if not np.any(keep):
            local_ind = np.asarray([i], dtype=np.int64)
        else:
            local_ind = local_ind[keep]
        m = min(width, len(local_ind))
        nbr_idx[i, :m] = local_ind[:m]
        nbr_mask[i, :m] = True
    return nbr_idx.astype(np.int64), nbr_mask.astype(bool)


def _masked_neighbor_prob_stats(prob: np.ndarray, nbr_idx: np.ndarray, nbr_mask: np.ndarray) -> np.ndarray:
    n = int(len(prob))
    if n == 0:
        return np.zeros((0, 5), dtype=np.float32)
    if nbr_idx.ndim != 2 or nbr_mask.ndim != 2 or nbr_idx.shape != nbr_mask.shape:
        return np.zeros((n, 5), dtype=np.float32)
    p = np.asarray(prob, dtype=np.float32)
    vals = p[np.clip(nbr_idx, 0, max(n - 1, 0))]
    mask = np.asarray(nbr_mask, dtype=bool)
    count = np.maximum(mask.sum(axis=1, keepdims=True).astype(np.float32), 1.0)
    vals_zero = np.where(mask, vals, 0.0)
    mean = vals_zero.sum(axis=1, keepdims=True) / count
    max_v = np.where(mask, vals, -np.inf).max(axis=1, keepdims=True)
    min_v = np.where(mask, vals, np.inf).min(axis=1, keepdims=True)
    max_v = np.where(np.isfinite(max_v), max_v, p.reshape(-1, 1))
    min_v = np.where(np.isfinite(min_v), min_v, p.reshape(-1, 1))
    var = np.where(mask, (vals - mean) ** 2, 0.0).sum(axis=1, keepdims=True) / count
    std = np.sqrt(np.maximum(var, 0.0))
    center_delta = p.reshape(-1, 1) - mean
    return np.concatenate([mean, max_v, min_v, std, center_delta], axis=1).astype(np.float32)


def _fragment_run_prob_features(record: Dict[str, object], prob: np.ndarray, order_window: int) -> np.ndarray:
    """Local same-fragment run descriptors from raw probability only.

    These are input features, not post-processing. They expose whether a token is
    supported by a short ordered run of similar evidence inside its own fragment,
    while allowing mixed fragments to keep different local decisions.
    """
    ds = record["downsampled"]
    n = int(len(prob))
    if n == 0:
        return np.zeros((0, 8), dtype=np.float32)
    p = np.clip(np.asarray(prob, dtype=np.float32), 0.0, 1.0)
    frag = np.asarray(ds.get("fragment_id", np.full(n, -1, dtype=np.int32)), dtype=np.int64)
    orig = np.asarray(ds.get("orig_index", np.arange(n, dtype=np.int64)), dtype=np.int64)
    feat_raw = np.asarray(ds.get("features", np.zeros((n, len(DOWNSAMPLED_FEATURE_NAMES)), dtype=np.float32)), dtype=np.float32)
    if feat_raw.ndim == 2 and feat_raw.shape[1] > DOWNSAMPLED_FEATURE_NAMES.index("token_order_norm"):
        token_order = feat_raw[:, DOWNSAMPLED_FEATURE_NAMES.index("token_order_norm")]
    else:
        token_order = np.arange(n, dtype=np.float32)
    out = np.zeros((n, 8), dtype=np.float32)
    w = max(1, int(order_window))
    high_thr = 0.35
    for fid in np.unique(frag):
        idx = np.where(frag == fid)[0]
        if len(idx) == 0:
            continue
        local_order = np.lexsort((orig[idx], token_order[idx]))
        ordered = idx[local_order]
        vals = p[ordered]
        high = vals >= high_thr
        L = len(ordered)
        for pos, center_idx in enumerate(ordered):
            lo = max(0, pos - w)
            hi = min(L, pos + w + 1)
            local_vals = vals[lo:hi]
            local_high = high[lo:hi]
            left_vals = vals[lo:pos]
            right_vals = vals[pos + 1:hi]
            center_local = pos - lo
            left = pos
            while left - 1 >= lo and high[left - 1]:
                left -= 1
            right = pos
            while right + 1 < hi and high[right + 1]:
                right += 1
            center_run = (right - left + 1) if high[pos] else 0
            best_run = 0
            cur = 0
            for flag in local_high:
                if flag:
                    cur += 1
                    best_run = max(best_run, cur)
                else:
                    cur = 0
            denom = float(max(1, 2 * w + 1))
            local_mean = float(np.mean(local_vals)) if len(local_vals) else float(vals[pos])
            left_mean = float(np.mean(left_vals)) if len(left_vals) else float(vals[pos])
            right_mean = float(np.mean(right_vals)) if len(right_vals) else float(vals[pos])
            high_frac = float(np.mean(local_high)) if len(local_high) else 0.0
            out[int(center_idx)] = np.asarray(
                [
                    local_mean,
                    left_mean,
                    right_mean,
                    high_frac,
                    float(center_run) / denom,
                    float(best_run) / denom,
                    1.0 if high[pos] else 0.0,
                    float(vals[pos] - 0.5 * (left_mean + right_mean)),
                ],
                dtype=np.float32,
            )
    return out.astype(np.float32)


def build_superline_transformer_input(record: Dict[str, object], feat_mean: np.ndarray, feat_std: np.ndarray, cfg: Config, prob_key: str = "prob") -> Dict[str, np.ndarray]:
    """Build one complete-file token set for superline-aware Transformer refinement.

    Node = one downsampled local-patch representative token.
    Features = standardized token attributes plus evidence and normalized XYZ.
    Attention = same-fragment ordered local window only.
    """
    ds = record["downsampled"]
    y = np.asarray(ds.get("label", np.zeros(0, dtype=np.int64)), dtype=np.int64)
    n = int(len(y))
    feat_dim = len(active_downsampled_feature_names(cfg))
    extra_dim = token_transformer_extra_feature_dim(cfg)
    if n == 0:
        win = 2 * int(getattr(cfg, "token_transformer_order_window", 8)) + 1
        spatial_win = max(1, int(getattr(cfg, "token_transformer_spatial_k", 12))) + 1
        return {
            "x": np.zeros((0, feat_dim + 5 + extra_dim), dtype=np.float32),
            "nbr_idx": np.zeros((0, win), dtype=np.int64),
            "nbr_mask": np.zeros((0, win), dtype=bool),
            "spatial_nbr_idx": np.zeros((0, spatial_win), dtype=np.int64),
            "spatial_nbr_mask": np.zeros((0, spatial_win), dtype=bool),
            "fragment_id": np.zeros(0, dtype=np.int64),
            "feature_dim": feat_dim,
            "y": y,
        }

    feat_raw = downsampled_feature_matrix(ds, cfg)
    feat_x = ((feat_raw - feat_mean) / feat_std).astype(np.float32)
    prob = np.asarray(record.get(prob_key, np.zeros(n, dtype=np.float32)), dtype=np.float32)
    if len(prob) != n:
        prob = np.zeros(n, dtype=np.float32)
    raw_logit = _safe_prob_to_logit(prob).reshape(-1, 1)
    prob_col = prob.reshape(-1, 1).astype(np.float32)

    xyz = np.asarray(ds.get("xyz", np.zeros((n, 3), dtype=np.float32)), dtype=np.float32)
    base_idx = DOWNSAMPLED_FEATURE_NAMES.index("base_spacing")
    base_vals = feat_raw[:, base_idx] if feat_raw.ndim == 2 and feat_raw.shape[1] > base_idx else np.asarray([1.0], dtype=np.float32)
    base_vals = base_vals[np.isfinite(base_vals) & (base_vals > 1e-8)]
    base_spacing = float(np.median(base_vals)) if len(base_vals) else 1.0
    if not np.isfinite(base_spacing) or base_spacing <= 0:
        base_spacing = 1.0
    center = np.mean(xyz, axis=0, keepdims=True).astype(np.float32)
    xyz_norm = ((xyz - center) / max(base_spacing, 1e-6)).astype(np.float32)
    if bool(getattr(cfg, "use_token_polar_features", False)):
        xy = xyz_norm[:, :2].astype(np.float32)
        radius = np.linalg.norm(xy, axis=1, keepdims=True).astype(np.float32)
        theta = np.arctan2(xy[:, 1:2], xy[:, 0:1]).astype(np.float32)
        polar_feat = np.concatenate(
            [
                np.tanh(radius / 20.0).astype(np.float32),
                np.sin(theta).astype(np.float32),
                np.cos(theta).astype(np.float32),
                np.tanh(xyz_norm[:, 2:3] / 20.0).astype(np.float32),
            ],
            axis=1,
        )

    nbr_idx, nbr_mask = build_same_fragment_window_indices(record, int(getattr(cfg, "token_transformer_order_window", 8)))
    spatial_idx, spatial_mask = build_spatial_knn_window_indices(record, cfg)
    parts = [feat_x, raw_logit, prob_col, xyz_norm]
    if bool(getattr(cfg, "use_token_polar_features", False)):
        parts.append(polar_feat)
    if bool(getattr(cfg, "use_token_neighbor_prob_features", False)):
        same_stats = _masked_neighbor_prob_stats(prob, nbr_idx, nbr_mask)
        spatial_stats = _masked_neighbor_prob_stats(prob, spatial_idx, spatial_mask)
        parts.append(np.concatenate([same_stats, spatial_stats], axis=1).astype(np.float32))
    if bool(getattr(cfg, "use_token_run_prob_features", False)):
        parts.append(
            _fragment_run_prob_features(
                record,
                prob,
                int(getattr(cfg, "token_transformer_order_window", 8)),
            )
        )
    if bool(getattr(cfg, "use_token_global_context_features", False)):
        prob_safe = np.clip(prob.astype(np.float32), 0.0, 1.0)
        q25, q50, q75 = np.quantile(prob_safe, [0.25, 0.50, 0.75]).astype(np.float32)
        xyz_extent = np.ptp(xyz_norm.astype(np.float32), axis=0) if len(xyz_norm) else np.zeros(3, dtype=np.float32)
        global_feat = np.array(
            [
                float(np.mean(prob_safe)),
                float(np.std(prob_safe)),
                float(q25),
                float(q50),
                float(q75),
                float(np.mean(prob_safe >= 0.35)),
                float(np.mean(prob_safe >= 0.50)),
                float(np.tanh(np.log1p(float(n)) / 8.0)),
                float(np.tanh(np.linalg.norm(xyz_extent[:2]) / 60.0)),
                float(np.tanh(float(xyz_extent[2]) / 30.0)),
            ],
            dtype=np.float32,
        ).reshape(1, -1)
        parts.append(np.repeat(global_feat, n, axis=0).astype(np.float32))
    node_x = np.concatenate(parts, axis=1).astype(np.float32)
    return {
        "x": node_x,
        "nbr_idx": nbr_idx,
        "nbr_mask": nbr_mask,
        "spatial_nbr_idx": spatial_idx,
        "spatial_nbr_mask": spatial_mask,
        "fragment_id": np.asarray(ds.get("fragment_id", np.arange(n, dtype=np.int64)), dtype=np.int64),
        "feature_dim": feat_dim,
        "y": y,
    }


class SameFragmentWindowAttentionLayer(nn.Module):
    """Transformer-style local attention over same-fragment ordered windows."""
    def __init__(self, hidden_dim: int, dropout: float):
        super().__init__()
        self.q = nn.Linear(hidden_dim, hidden_dim)
        self.k = nn.Linear(hidden_dim, hidden_dim)
        self.v = nn.Linear(hidden_dim, hidden_dim)
        self.out = nn.Linear(hidden_dim, hidden_dim)
        self.norm1 = nn.LayerNorm(hidden_dim)
        self.norm2 = nn.LayerNorm(hidden_dim)
        self.ffn = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim * 2),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim * 2, hidden_dim),
        )
        self.dropout = nn.Dropout(dropout)

    def forward(self, h: torch.Tensor, nbr_idx: torch.Tensor, nbr_mask: torch.Tensor) -> torch.Tensor:
        # h: (N,H), nbr_idx: (N,W), nbr_mask: (N,W)
        if h.numel() == 0:
            return h
        q = self.q(h)  # (N,H)
        k = self.k(h)
        v = self.v(h)
        # Wide diagnostic windows can otherwise materialize N x W x H tensors
        # larger than GPU memory.  Attention rows are independent, so chunking
        # the center-token dimension preserves the exact effective neighbors.
        max_pairs_per_chunk = 1_000_000
        width = max(1, int(nbr_idx.shape[1]))
        chunk_rows = max(1, max_pairs_per_chunk // width)
        msg_parts = []
        for start in range(0, int(h.shape[0]), chunk_rows):
            end = min(int(h.shape[0]), start + chunk_rows)
            idx_part = nbr_idx[start:end]
            mask_part = nbr_mask[start:end]
            k_n = k[idx_part]
            v_n = v[idx_part]
            scores = torch.sum(q[start:end].unsqueeze(1) * k_n, dim=-1) / math.sqrt(max(1, q.shape[-1]))
            scores = scores.masked_fill(~mask_part, -1e9)
            attn = torch.softmax(scores, dim=1)
            # Safety for all-masked rows; construction should always include self.
            attn = torch.where(torch.isfinite(attn), attn, torch.zeros_like(attn))
            msg_parts.append(torch.sum(attn.unsqueeze(-1) * v_n, dim=1))
        msg = torch.cat(msg_parts, dim=0)
        h = self.norm1(h + self.dropout(self.out(msg)))
        h = self.norm2(h + self.dropout(self.ffn(h)))
        return h


class SuperlineTokenTransformerRefiner(nn.Module):
    """Residual token refiner using superline-aware local self-attention.

    It predicts delta_logit and keeps the local-patch/token-attribute classifier as the
    base model: refined_logit = raw_logit + delta_logit.
    """
    def __init__(
        self,
        in_dim: int,
        hidden_dim: int,
        num_layers: int,
        dropout: float,
        context_mode: str = "same_fragment",
        spatial_residual_weight: float = 1.0,
        raw_prob_col_idx: int = 0,
        connectivity_gate_mode: str = "none",
        connectivity_gate_strength: float = 0.0,
        edge_message_weight: float = 0.0,
    ):
        super().__init__()
        self.context_mode = str(context_mode or "same_fragment").lower()
        self.spatial_residual_weight = float(spatial_residual_weight)
        self.raw_prob_col_idx = int(raw_prob_col_idx)
        self.raw_logit_col_idx = max(0, self.raw_prob_col_idx - 1)
        self.connectivity_gate_mode = str(connectivity_gate_mode or "none").lower()
        self.connectivity_gate_strength = float(connectivity_gate_strength)
        self.edge_message_weight = float(edge_message_weight)
        self.input_proj = nn.Sequential(
            nn.Linear(in_dim, hidden_dim),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
        )
        self.layers = nn.ModuleList([
            SameFragmentWindowAttentionLayer(hidden_dim, dropout) for _ in range(max(1, int(num_layers)))
        ])
        spatial_modes = ("dual_context", "same_plus_spatial", "spatial_knn", "dual_context_gated", "dual_context_fragment_mixer", "dual_context_crf")
        self.spatial_layers = nn.ModuleList([
            SameFragmentWindowAttentionLayer(hidden_dim, dropout) for _ in range(max(1, int(num_layers)))
        ]) if self.context_mode in spatial_modes else nn.ModuleList()
        self.spatial_gates = nn.ModuleList()
        if self.context_mode == "dual_context_gated":
            for _ in range(max(1, int(num_layers))):
                gate = nn.Sequential(
                    nn.Linear(hidden_dim * 3, hidden_dim),
                    nn.ReLU(inplace=True),
                    nn.Dropout(dropout),
                    nn.Linear(hidden_dim, 1),
                )
                nn.init.constant_(gate[-1].bias, -1.0986123)
                self.spatial_gates.append(gate)
        self.fragment_mixer = None
        if self.context_mode == "dual_context_fragment_mixer":
            self.fragment_mixer = nn.Sequential(
                nn.Linear(hidden_dim * 4, hidden_dim),
                nn.ReLU(inplace=True),
                nn.Dropout(dropout),
                nn.Linear(hidden_dim, hidden_dim),
            )
            self.fragment_norm = nn.LayerNorm(hidden_dim)
        if self.context_mode == "dual_context_crf":
            self.crf_same_logit = nn.Parameter(torch.tensor(-2.1972246, dtype=torch.float32))
            self.crf_spatial_logit = nn.Parameter(torch.tensor(-2.9444390, dtype=torch.float32))
        self.delta_head = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, 1),
        )
        self.edge_head = nn.Sequential(
            nn.Linear(hidden_dim * 3, max(24, hidden_dim // 2)),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(max(24, hidden_dim // 2), 1),
        )
        self.connectivity_gate = None
        if self.connectivity_gate_mode == "support_gate" and self.connectivity_gate_strength > 0.0:
            self.connectivity_gate = nn.Sequential(
                nn.Linear(hidden_dim + 4, max(16, hidden_dim // 2)),
                nn.ReLU(inplace=True),
                nn.Dropout(dropout),
                nn.Linear(max(16, hidden_dim // 2), 1),
            )
            nn.init.constant_(self.connectivity_gate[-1].bias, 1.3862944)
        elif self.connectivity_gate_mode == "fragment_gate" and self.connectivity_gate_strength > 0.0:
            self.connectivity_gate = nn.Sequential(
                nn.Linear(hidden_dim * 3, max(16, hidden_dim // 2)),
                nn.ReLU(inplace=True),
                nn.Dropout(dropout),
                nn.Linear(max(16, hidden_dim // 2), 1),
            )
            nn.init.constant_(self.connectivity_gate[-1].bias, 1.3862944)

    def forward(
        self,
        x: torch.Tensor,
        nbr_idx: torch.Tensor,
        nbr_mask: torch.Tensor,
        spatial_nbr_idx: Optional[torch.Tensor] = None,
        spatial_nbr_mask: Optional[torch.Tensor] = None,
        fragment_id: Optional[torch.Tensor] = None,
        return_edges: bool = False,
    ) -> torch.Tensor | Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        h = self.input_proj(x)
        if self.context_mode == "spatial_knn" and spatial_nbr_idx is not None and spatial_nbr_mask is not None:
            for layer in self.spatial_layers:
                h = layer(h, spatial_nbr_idx, spatial_nbr_mask)
        elif self.context_mode in ("dual_context", "same_plus_spatial", "dual_context_gated", "dual_context_fragment_mixer", "dual_context_crf") and spatial_nbr_idx is not None and spatial_nbr_mask is not None:
            for layer_i, (same_layer, spatial_layer) in enumerate(zip(self.layers, self.spatial_layers)):
                h = same_layer(h, nbr_idx, nbr_mask)
                if self.spatial_residual_weight <= 0.0:
                    continue
                spatial_h = spatial_layer(h, spatial_nbr_idx, spatial_nbr_mask)
                if self.context_mode == "dual_context_gated" and layer_i < len(self.spatial_gates):
                    gate_in = torch.cat([h, spatial_h, spatial_h - h], dim=1)
                    gate = torch.sigmoid(self.spatial_gates[layer_i](gate_in)).squeeze(1)
                    h = h + (self.spatial_residual_weight * gate).unsqueeze(1) * (spatial_h - h)
                else:
                    h = h + self.spatial_residual_weight * (spatial_h - h)
        else:
            for layer in self.layers:
                h = layer(h, nbr_idx, nbr_mask)
        edge_logits = None
        edge_valid = None
        need_edges = bool(return_edges or self.edge_message_weight > 0.0)
        if need_edges and nbr_idx is not None and nbr_mask is not None and nbr_idx.numel() > 0:
            center = h.unsqueeze(1).expand(-1, nbr_idx.shape[1], -1)
            neigh = h[nbr_idx]
            edge_in = torch.cat([center, neigh, torch.abs(center - neigh)], dim=-1)
            edge_logits = self.edge_head(edge_in).squeeze(-1)
            row_idx = torch.arange(h.shape[0], device=h.device).unsqueeze(1).expand_as(nbr_idx)
            edge_valid = nbr_mask & (nbr_idx != row_idx)
            edge_logits = edge_logits.masked_fill(~edge_valid, -1e4)
            if self.edge_message_weight > 0.0 and torch.any(edge_valid):
                edge_weight = torch.sigmoid(edge_logits) * edge_valid.to(dtype=h.dtype)
                denom = torch.clamp(edge_weight.sum(dim=1, keepdim=True), min=1.0)
                msg = torch.sum(edge_weight.unsqueeze(-1) * neigh, dim=1) / denom
                h = h + self.edge_message_weight * msg
        if (
            self.fragment_mixer is not None
            and fragment_id is not None
            and fragment_id.numel() == h.shape[0]
        ):
            _, inv = torch.unique(fragment_id, sorted=False, return_inverse=True)
            frag_count = int(torch.max(inv).item()) + 1 if inv.numel() else 0
            if frag_count > 0:
                frag_sum = h.new_zeros((frag_count, h.shape[1]))
                frag_sum.index_add_(0, inv, h)
                count = torch.bincount(inv, minlength=frag_count).to(dtype=h.dtype, device=h.device).clamp_min(1.0)
                frag_mean = frag_sum / count.unsqueeze(1)
                pooled = frag_mean[inv]
                centered = h - pooled
                frag_msg = self.fragment_mixer(torch.cat([h, pooled, torch.abs(centered), centered], dim=1))
                h = self.fragment_norm(h + frag_msg)
        delta = self.delta_head(h).squeeze(1)
        if (
            self.context_mode == "dual_context_crf"
            and x.shape[1] > self.raw_logit_col_idx
            and nbr_idx is not None
            and nbr_mask is not None
            and spatial_nbr_idx is not None
            and spatial_nbr_mask is not None
        ):
            refined_logit = x[:, self.raw_logit_col_idx] + delta
            p = torch.sigmoid(refined_logit)

            def _masked_prob_mean(idx: torch.Tensor, mask: torch.Tensor) -> torch.Tensor:
                valid = mask.to(dtype=p.dtype)
                if valid.shape[1] > 0:
                    row_idx_local = torch.arange(p.shape[0], device=p.device).unsqueeze(1).expand_as(idx)
                    valid = torch.where(idx == row_idx_local, torch.zeros_like(valid), valid)
                count = torch.clamp(valid.sum(dim=1), min=1.0)
                return (p[idx] * valid).sum(dim=1) / count

            same_mean = _masked_prob_mean(nbr_idx, nbr_mask)
            spatial_mean = _masked_prob_mean(spatial_nbr_idx, spatial_nbr_mask)
            same_w = torch.sigmoid(self.crf_same_logit)
            spatial_w = torch.sigmoid(self.crf_spatial_logit)
            target_p = torch.clamp(
                (same_w * same_mean + spatial_w * spatial_mean) / torch.clamp(same_w + spatial_w, min=1e-6),
                1e-4,
                1.0 - 1e-4,
            )
            target_logit = torch.logit(target_p)
            correction = torch.clamp(same_w + spatial_w, 0.0, 0.5) * (target_logit - refined_logit)
            delta = delta + correction
        if (
            self.connectivity_gate is not None
            and self.connectivity_gate_mode == "support_gate"
            and spatial_nbr_idx is not None
            and spatial_nbr_mask is not None
            and x.shape[1] > self.raw_prob_col_idx
        ):
            center_prob = torch.clamp(x[:, self.raw_prob_col_idx], 0.0, 1.0)
            valid = spatial_nbr_mask.to(dtype=x.dtype)
            if valid.shape[1] > 0:
                valid[:, 0] = 0.0
            count = torch.clamp(valid.sum(dim=1), min=1.0)
            nbr_prob = center_prob[spatial_nbr_idx]
            nbr_mean = (nbr_prob * valid).sum(dim=1) / count
            count_norm = torch.clamp(count / max(float(spatial_nbr_idx.shape[1] - 1), 1.0), 0.0, 1.0)
            gate_in = torch.cat(
                [
                    h,
                    center_prob.unsqueeze(1),
                    nbr_mean.unsqueeze(1),
                    (center_prob - nbr_mean).unsqueeze(1),
                    count_norm.unsqueeze(1),
                ],
                dim=1,
            )
            gate = torch.sigmoid(self.connectivity_gate(gate_in)).squeeze(1)
            positive_delta = torch.relu(delta)
            delta = delta - self.connectivity_gate_strength * (1.0 - gate) * positive_delta
        elif (
            self.connectivity_gate is not None
            and self.connectivity_gate_mode == "fragment_gate"
            and fragment_id is not None
            and fragment_id.numel() == h.shape[0]
        ):
            _, inv = torch.unique(fragment_id, sorted=False, return_inverse=True)
            frag_count = int(torch.max(inv).item()) + 1 if inv.numel() else 0
            if frag_count > 0:
                frag_sum = h.new_zeros((frag_count, h.shape[1]))
                frag_sum.index_add_(0, inv, h)
                count = torch.bincount(inv, minlength=frag_count).to(dtype=h.dtype, device=h.device).clamp_min(1.0)
                frag_mean = frag_sum / count.unsqueeze(1)
                pooled = frag_mean[inv]
                gate_in = torch.cat([h, pooled, torch.abs(h - pooled)], dim=1)
                gate = torch.sigmoid(self.connectivity_gate(gate_in)).squeeze(1)
                positive_delta = torch.relu(delta)
                delta = delta - self.connectivity_gate_strength * (1.0 - gate) * positive_delta
        if return_edges:
            if edge_logits is None or edge_valid is None:
                edge_logits = torch.zeros((x.shape[0], 1), dtype=x.dtype, device=x.device)
                edge_valid = torch.zeros((x.shape[0], 1), dtype=torch.bool, device=x.device)
            return delta, edge_logits, edge_valid
        return delta


def boundary_structure_aux_loss(
    logits: torch.Tensor,
    y: torch.Tensor,
    nbr_idx: torch.Tensor,
    nbr_mask: torch.Tensor,
    fragment_id: torch.Tensor,
) -> torch.Tensor:
    """Lightweight supervised continuity/completeness loss for boundary evidence."""
    if logits.numel() == 0:
        return logits.sum() * 0.0
    p = torch.sigmoid(logits)
    pos = y > 0.5
    losses = []
    if torch.any(pos):
        losses.append(torch.mean((1.0 - p[pos]) ** 2))

    valid = nbr_mask.clone()
    if valid.shape[1] > 0:
        valid[:, 0] = False
    center_idx = torch.arange(logits.shape[0], device=logits.device).unsqueeze(1).expand_as(nbr_idx)
    same_fragment = fragment_id[center_idx] == fragment_id[nbr_idx]
    pos_pair = pos.unsqueeze(1) & pos[nbr_idx] & valid & same_fragment
    if torch.any(pos_pair):
        center_p = p.unsqueeze(1).expand_as(nbr_idx.float())
        neigh_p = p[nbr_idx]
        losses.append(torch.mean((center_p[pos_pair] - neigh_p[pos_pair]) ** 2))

    frag_losses = []
    for fid in torch.unique(fragment_id):
        mask = fragment_id == fid
        if not torch.any(mask):
            continue
        target = torch.mean(y[mask])
        if target > 0.0:
            frag_losses.append((torch.mean(p[mask]) - target) ** 2)
    if frag_losses:
        losses.append(torch.stack(frag_losses).mean())
    if not losses:
        return logits.sum() * 0.0
    return torch.stack(losses).mean()


def spatial_connectivity_aux_loss(
    logits: torch.Tensor,
    y: torch.Tensor,
    spatial_nbr_idx: torch.Tensor,
    spatial_nbr_mask: torch.Tensor,
) -> torch.Tensor:
    """Supervised spatial-connectivity prior for evidence-only token prediction.

    This is a training-time prior only: isolated synthetic negatives with little
    positive support in their spatial neighborhood are penalized more strongly,
    while true boundary tokens are encouraged to remain locally continuous.
    """
    if logits.numel() == 0 or spatial_nbr_idx.numel() == 0:
        return logits.sum() * 0.0
    p = torch.sigmoid(logits)
    yb = y > 0.5
    valid = spatial_nbr_mask.clone()
    if valid.shape[1] > 0:
        valid[:, 0] = False
    valid_f = valid.to(dtype=p.dtype)
    count = torch.clamp(valid_f.sum(dim=1), min=1.0)
    nbr_y = y[spatial_nbr_idx].to(dtype=p.dtype)
    nbr_p = p[spatial_nbr_idx]
    nbr_pos_frac = (nbr_y * valid_f).sum(dim=1) / count
    nbr_prob_mean = (nbr_p * valid_f).sum(dim=1) / count

    losses = []
    # Penalize negative islands that have no labeled boundary support nearby.
    isolated_neg = (~yb) & (nbr_pos_frac < 0.08)
    if torch.any(isolated_neg):
        island_weight = torch.clamp(1.0 - nbr_prob_mean[isolated_neg], min=0.25, max=1.0)
        losses.append(torch.mean(island_weight * (p[isolated_neg] ** 2)))

    # Encourage positive boundary tokens with positive neighbors to stay active.
    supported_pos = yb & (nbr_pos_frac > 0.0)
    if torch.any(supported_pos):
        support = torch.clamp(nbr_pos_frac[supported_pos], min=0.2, max=1.0)
        losses.append(torch.mean(support * ((1.0 - p[supported_pos]) ** 2)))

    # Smooth probabilities only along positive-positive spatial pairs.
    pos_pair = yb.unsqueeze(1) & yb[spatial_nbr_idx] & valid
    if torch.any(pos_pair):
        center_p = p.unsqueeze(1).expand_as(nbr_p)
        losses.append(torch.mean((center_p[pos_pair] - nbr_p[pos_pair]) ** 2))

    if not losses:
        return logits.sum() * 0.0
    return torch.stack(losses).mean()


def edge_continuity_aux_loss(
    edge_logits: torch.Tensor,
    edge_valid: torch.Tensor,
    y: torch.Tensor,
    nbr_idx: torch.Tensor,
) -> torch.Tensor:
    """Supervise same-fragment neighbor continuity with synthetic labels.

    Positive edges connect two labeled boundary tokens. Negative edges cover
    mixed or non-boundary pairs in the same local fragment window. This makes
    the token refiner learn continuity before inference, instead of filtering
    isolated fragments after prediction.
    """
    if edge_logits.numel() == 0 or edge_valid.numel() == 0 or not torch.any(edge_valid):
        return edge_logits.sum() * 0.0
    yy = y > 0.5
    edge_y = (yy.unsqueeze(1) & yy[nbr_idx]).to(dtype=edge_logits.dtype)
    valid = edge_valid
    logits = edge_logits[valid]
    target = edge_y[valid]
    if logits.numel() == 0:
        return edge_logits.sum() * 0.0
    pos = torch.clamp(target.sum(), min=1.0)
    neg = torch.clamp((1.0 - target).sum(), min=1.0)
    pos_weight = torch.clamp(neg / pos, min=1.0, max=20.0)
    return F.binary_cross_entropy_with_logits(logits, target, pos_weight=pos_weight)


def same_fragment_connectivity_aux_loss(
    logits: torch.Tensor,
    y: torch.Tensor,
    nbr_idx: torch.Tensor,
    nbr_mask: torch.Tensor,
) -> torch.Tensor:
    """Gentle same-fragment continuity prior on token probabilities.

    This avoids a separate edge classifier. It directly discourages isolated
    high-confidence negative tokens and encourages positive tokens with local
    positive support to remain active.
    """
    if logits.numel() == 0 or nbr_idx.numel() == 0:
        return logits.sum() * 0.0
    p = torch.sigmoid(logits)
    yb = y > 0.5
    row_idx = torch.arange(logits.shape[0], device=logits.device).unsqueeze(1).expand_as(nbr_idx)
    valid = nbr_mask & (nbr_idx != row_idx)
    if not torch.any(valid):
        return logits.sum() * 0.0
    valid_f = valid.to(dtype=p.dtype)
    count = torch.clamp(valid_f.sum(dim=1), min=1.0)
    nbr_y = y[nbr_idx].to(dtype=p.dtype)
    nbr_p = p[nbr_idx]
    nbr_pos_frac = (nbr_y * valid_f).sum(dim=1) / count
    nbr_prob_mean = (nbr_p * valid_f).sum(dim=1) / count
    losses = []

    isolated_neg = (~yb) & (nbr_pos_frac <= 0.0)
    if torch.any(isolated_neg):
        weight = torch.clamp(1.0 - nbr_prob_mean[isolated_neg], min=0.25, max=1.0)
        losses.append(torch.mean(weight * (p[isolated_neg] ** 2)))

    supported_pos = yb & (nbr_pos_frac > 0.0)
    if torch.any(supported_pos):
        support = torch.clamp(nbr_pos_frac[supported_pos], min=0.2, max=1.0)
        losses.append(torch.mean(support * ((1.0 - p[supported_pos]) ** 2)))

    pos_pair = yb.unsqueeze(1) & yb[nbr_idx] & valid
    if torch.any(pos_pair):
        center_p = p.unsqueeze(1).expand_as(nbr_p)
        losses.append(torch.mean((center_p[pos_pair] - nbr_p[pos_pair]) ** 2))

    if not losses:
        return logits.sum() * 0.0
    return torch.stack(losses).mean()


def perturb_token_transformer_input_for_consistency(x: torch.Tensor, feature_dim: int, cfg: Config) -> torch.Tensor:
    """Apply label-preserving token feature jitter for synthetic consistency training."""
    feat_noise = float(getattr(cfg, "token_transformer_consistency_feature_noise_std", 0.0))
    xyz_noise = float(getattr(cfg, "token_transformer_consistency_xyz_noise_std", 0.0))
    if feat_noise <= 0.0 and xyz_noise <= 0.0:
        return x
    x_aug = x.clone()
    if feature_dim > 0 and feat_noise > 0.0:
        x_aug[:, :feature_dim] = x_aug[:, :feature_dim] + torch.randn_like(x_aug[:, :feature_dim]) * feat_noise
    # Layout: [token_features, raw_logit, raw_prob, xyz_norm, optional extras].
    xyz_start = int(feature_dim) + 2
    xyz_end = min(x_aug.shape[1], xyz_start + 3)
    if xyz_end > xyz_start and xyz_noise > 0.0:
        x_aug[:, xyz_start:xyz_end] = x_aug[:, xyz_start:xyz_end] + torch.randn_like(x_aug[:, xyz_start:xyz_end]) * xyz_noise
    return x_aug


def apply_token_input_group_dropout(x: torch.Tensor, feature_dim: int, cfg: Config) -> torch.Tensor:
    """Drop small input groups during token-refiner training to reduce synthetic shortcuts."""
    raw_drop = min(max(float(getattr(cfg, "token_transformer_raw_evidence_dropout", 0.0)), 0.0), 1.0)
    xyz_drop = min(max(float(getattr(cfg, "token_transformer_xyz_dropout", 0.0)), 0.0), 1.0)
    feat_drop = min(max(float(getattr(cfg, "token_transformer_feature_dropout", 0.0)), 0.0), 1.0)
    if raw_drop <= 0.0 and xyz_drop <= 0.0 and feat_drop <= 0.0:
        return x

    x_aug = x.clone()
    n = int(x_aug.shape[0])
    if n <= 0:
        return x_aug

    if feature_dim > 0 and feat_drop > 0.0:
        feat_mask = (torch.rand((n, feature_dim), device=x_aug.device) >= feat_drop).to(dtype=x_aug.dtype)
        x_aug[:, :feature_dim] = x_aug[:, :feature_dim] * feat_mask

    # Layout: [token_features, raw_logit, raw_prob, xyz_norm, optional extras].
    raw_logit_idx = int(feature_dim)
    raw_prob_idx = int(feature_dim) + 1
    if x_aug.shape[1] > raw_prob_idx and raw_drop > 0.0:
        raw_mask = torch.rand((n,), device=x_aug.device) < raw_drop
        if torch.any(raw_mask):
            x_aug[raw_mask, raw_logit_idx] = 0.0
            x_aug[raw_mask, raw_prob_idx] = 0.5

    xyz_start = int(feature_dim) + 2
    xyz_end = min(int(x_aug.shape[1]), xyz_start + 3)
    if xyz_end > xyz_start and xyz_drop > 0.0:
        xyz_mask = torch.rand((n,), device=x_aug.device) < xyz_drop
        if torch.any(xyz_mask):
            x_aug[xyz_mask, xyz_start:xyz_end] = 0.0

    return x_aug


def average_state_dicts(ranked_states: List[Tuple[float, Dict[str, torch.Tensor]]], top_k: int) -> Dict[str, torch.Tensor]:
    """Average floating-point tensors from top synthetic-val checkpoints."""
    selected = ranked_states[:max(1, min(int(top_k), len(ranked_states)))]
    if not selected:
        return {}
    out: Dict[str, torch.Tensor] = {}
    keys = selected[0][1].keys()
    for key in keys:
        vals = [state[key] for _, state in selected]
        if torch.is_floating_point(vals[0]):
            out[key] = torch.stack([v.to(dtype=torch.float32) for v in vals], dim=0).mean(dim=0).to(dtype=vals[0].dtype)
        else:
            out[key] = vals[0].clone()
    return out


def _base_spacing_from_downsampled(ds: Dict[str, np.ndarray]) -> float:
    feat = np.asarray(ds.get("features", np.zeros((0, len(DOWNSAMPLED_FEATURE_NAMES)), dtype=np.float32)), dtype=np.float32)
    if feat.ndim == 2 and len(feat) and "base_spacing" in DOWNSAMPLED_FEATURE_NAMES:
        idx = DOWNSAMPLED_FEATURE_NAMES.index("base_spacing")
        vals = feat[:, idx]
        vals = vals[np.isfinite(vals) & (vals > 1e-8)]
        if len(vals):
            return float(np.median(vals))
    xyz = np.asarray(ds.get("xyz", np.zeros((0, 3), dtype=np.float32)), dtype=np.float32)
    return estimate_base_spacing(xyz) if len(xyz) > 1 else 1.0


def _connected_components_from_indices(xyz: np.ndarray, indices: np.ndarray, eps: float) -> List[np.ndarray]:
    """Connected components among selected token indices using 3D radius eps."""
    indices = np.asarray(indices, dtype=np.int64)
    if len(indices) == 0:
        return []
    pts = np.asarray(xyz, dtype=np.float32)[indices]
    if len(indices) == 1:
        return [indices.copy()]
    tree = cKDTree(pts)
    visited = np.zeros(len(indices), dtype=bool)
    comps: List[np.ndarray] = []
    for start in range(len(indices)):
        if visited[start]:
            continue
        queue = [start]
        visited[start] = True
        comp_local = []
        qpos = 0
        while qpos < len(queue):
            u = queue[qpos]
            qpos += 1
            comp_local.append(u)
            nbrs = tree.query_ball_point(pts[u], r=float(eps))
            for v in nbrs:
                if not visited[int(v)]:
                    visited[int(v)] = True
                    queue.append(int(v))
        comps.append(indices[np.asarray(comp_local, dtype=np.int64)])
    return comps


def compute_cluster_aware_token_features(
    record: Dict[str, object],
    feat_mean: np.ndarray,
    feat_std: np.ndarray,
    cfg: Config,
    prob_key: str = "token_transformer_prob",
) -> Tuple[np.ndarray, pd.DataFrame]:
    """Build per-token features for the V15.6 cluster-aware residual head.

    This is not a line/path/ring algorithm. It does not connect clusters or fit a contour.
    It simply summarizes the high-confidence 3D component that each high-confidence
    token belongs to, then lets a small synthetic-trained MLP learn whether that local
    cluster context should suppress or keep the existing PT probability.
    """
    ds = record["downsampled"]
    y = np.asarray(ds.get("label", np.zeros(0, dtype=np.int64)), dtype=np.int64)
    n = int(len(y))
    feat_raw = np.asarray(ds.get("features", np.zeros((n, len(DOWNSAMPLED_FEATURE_NAMES)), dtype=np.float32)), dtype=np.float32)
    if feat_raw.ndim != 2:
        feat_raw = np.zeros((n, len(DOWNSAMPLED_FEATURE_NAMES)), dtype=np.float32)
    feat_x = ((feat_raw - feat_mean) / feat_std).astype(np.float32) if len(feat_raw) else np.zeros((0, len(DOWNSAMPLED_FEATURE_NAMES)), dtype=np.float32)

    prob = np.asarray(record.get(prob_key, np.zeros(n, dtype=np.float32)), dtype=np.float32)
    if len(prob) != n:
        prob = np.zeros(n, dtype=np.float32)
    base_logit = _safe_prob_to_logit(prob).reshape(-1, 1)
    base_prob = prob.reshape(-1, 1).astype(np.float32)

    xyz = np.asarray(ds.get("xyz", np.zeros((n, 3), dtype=np.float32)), dtype=np.float32)
    rgb = normalize_rgb(np.asarray(ds.get("rgb", np.zeros((n, 3), dtype=np.float32)), dtype=np.float32))
    if len(rgb) != n:
        rgb = np.zeros((n, 3), dtype=np.float32)
    base_spacing = _base_spacing_from_downsampled(ds)
    bs = max(float(base_spacing), 1e-6)
    if len(xyz):
        xyz_center = np.median(xyz, axis=0)
        xyz_norm = (xyz - xyz_center[None, :]) / bs
        xyz_norm = np.clip(xyz_norm, -20.0, 20.0).astype(np.float32)
    else:
        xyz_norm = np.zeros((0, 3), dtype=np.float32)

    extra = np.zeros((n, len(CLUSTER_AWARE_FEATURE_NAMES)), dtype=np.float32)
    # columns 0..4 = base logit/prob/xyz.
    if n:
        extra[:, 0:1] = base_logit
        extra[:, 1:2] = base_prob
        extra[:, 2:5] = xyz_norm

    high_thr = float(getattr(cfg, "cluster_refiner_high_threshold", 0.70))
    eps = float(getattr(cfg, "cluster_refiner_eps_mm", 3.0))
    high_idx = np.where(prob >= high_thr)[0].astype(np.int64)
    comps = _connected_components_from_indices(xyz, high_idx, eps=eps) if n else []
    comps_sorted = sorted(comps, key=lambda arr: len(arr), reverse=True)
    n_high = max(1, len(high_idx))
    n_clusters = max(1, len(comps_sorted))

    rows = []
    for rank, idx in enumerate(comps_sorted):
        idx = np.asarray(idx, dtype=np.int64)
        pts = xyz[idx]
        probs_c = prob[idx]
        rgbs_c = rgb[idx] if len(rgb) else np.zeros((len(idx), 3), dtype=np.float32)
        st = pca_fragment_stats(pts)
        length_bs = float(st["length"]) / bs
        width_bs = float(st["width"]) / bs
        lwr_log = math.log1p(float(st["length"]) / (float(st["width"]) + 1e-6))
        density = float(len(idx)) / max(length_bs, 1.0)
        rgb_mean = np.mean(rgbs_c, axis=0).astype(np.float32) if len(idx) else np.zeros(3, dtype=np.float32)
        rgb_std = np.std(rgbs_c, axis=0).astype(np.float32) if len(idx) else np.zeros(3, dtype=np.float32)
        size = int(len(idx))
        rank_norm = float(rank / max(n_clusters - 1, 1))
        rank_inv = float(1.0 / (rank + 1.0))

        # 5..27 after base features.
        extra[idx, 5] = 1.0
        extra[idx, 6] = math.log1p(float(size))
        extra[idx, 7] = float(size) / float(n_high)
        extra[idx, 8] = rank_norm
        extra[idx, 9] = rank_inv
        extra[idx, 10] = 1.0 if rank == 0 else 0.0
        extra[idx, 11] = 1.0 if rank < 3 else 0.0
        extra[idx, 12] = float(np.mean(probs_c)) if len(probs_c) else 0.0
        extra[idx, 13] = float(np.max(probs_c)) if len(probs_c) else 0.0
        extra[idx, 14] = length_bs
        extra[idx, 15] = width_bs
        extra[idx, 16] = lwr_log
        extra[idx, 17] = float(st["linearness"])
        extra[idx, 18] = density
        if bool(getattr(cfg, "cluster_refiner_use_rgb", True)):
            extra[idx, 19:22] = rgb_mean[None, :]
            extra[idx, 22:25] = rgb_std[None, :]
            extra[idx, 25:28] = rgb[idx] - rgb_mean[None, :]

        gt = y[idx] if len(y) == n else np.zeros(len(idx), dtype=np.int64)
        rows.append({
            "domain": record.get("domain", ""),
            "split": record.get("split", ""),
            "subset": record.get("subset", ""),
            "sample_id": record.get("sample_id", ""),
            "threshold": high_thr,
            "eps_mm": eps,
            "cluster_rank": int(rank + 1),
            "cluster_points": size,
            "cluster_pos_ratio": float(np.mean(gt)) if len(gt) else 0.0,
            "cluster_mean_prob": float(np.mean(probs_c)) if len(probs_c) else 0.0,
            "cluster_max_prob": float(np.max(probs_c)) if len(probs_c) else 0.0,
            "cluster_length_bs": length_bs,
            "cluster_width_bs": width_bs,
            "cluster_lwr_log": lwr_log,
            "cluster_linearness": float(st["linearness"]),
            "cluster_density": density,
            "cluster_rgb_mean_r": float(rgb_mean[0]),
            "cluster_rgb_mean_g": float(rgb_mean[1]),
            "cluster_rgb_mean_b": float(rgb_mean[2]),
            "cluster_rgb_std_mean": float(np.mean(rgb_std)),
        })

    X = np.concatenate([feat_x, extra], axis=1).astype(np.float32) if n else np.zeros((0, len(DOWNSAMPLED_FEATURE_NAMES) + len(CLUSTER_AWARE_FEATURE_NAMES)), dtype=np.float32)
    return X, pd.DataFrame(rows)


class ClusterAwarePTRefiner(nn.Module):
    """Small residual MLP head for V15.6 cluster-aware PT refinement.

    The previous PT probability remains the base prediction. This head only predicts
    a residual delta_logit from token + high-confidence-cluster context:
        refined_logit = base_logit + delta_logit
    """
    def __init__(self, in_dim: int, hidden_dim: int, dropout: float):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(in_dim, hidden_dim),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, hidden_dim),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, 1),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x).squeeze(1)


def train_cluster_aware_pt_refiner(train_records: List[Dict[str, object]], val_records: List[Dict[str, object]], feat_mean: np.ndarray, feat_std: np.ndarray, cfg: Config):
    if not TORCH_AVAILABLE:
        raise RuntimeError(f"PyTorch not available: {TORCH_IMPORT_ERROR}")
    base_key = str(getattr(cfg, "cluster_refiner_base_prob_key", "token_transformer_prob"))
    train_items = []
    for r in train_records:
        if len(r["downsampled"]["label"]) == 0:
            continue
        x, _ = compute_cluster_aware_token_features(r, feat_mean, feat_std, cfg, prob_key=base_key)
        y = np.asarray(r["downsampled"]["label"], dtype=np.int64)
        base_prob = np.asarray(r.get(base_key, np.zeros(len(y), dtype=np.float32)), dtype=np.float32)
        train_items.append({"x": x, "y": y, "base_logit": _safe_prob_to_logit(base_prob)})
    if not train_items:
        raise ValueError("No non-empty train files for cluster-aware PT refiner.")

    in_dim = int(train_items[0]["x"].shape[1])
    device = torch.device(cfg.device)
    model = ClusterAwarePTRefiner(
        in_dim=in_dim,
        hidden_dim=int(getattr(cfg, "cluster_refiner_hidden_dim", 96)),
        dropout=float(getattr(cfg, "cluster_refiner_dropout", 0.10)),
    ).to(device)

    all_pos = sum(int(np.sum(item["y"] == 1)) for item in train_items)
    all_neg = sum(int(np.sum(item["y"] == 0)) for item in train_items)
    pos_weight = torch.tensor([max(float(all_neg), 1.0) / max(float(all_pos), 1.0)], dtype=torch.float32, device=device)
    crit = nn.BCEWithLogitsLoss(pos_weight=pos_weight, reduction="mean")
    opt = torch.optim.AdamW(
        model.parameters(),
        lr=float(getattr(cfg, "cluster_refiner_lr", 5e-4)),
        weight_decay=float(getattr(cfg, "cluster_refiner_weight_decay", 1e-4)),
    )

    epochs = int(getattr(cfg, "cluster_refiner_epochs", 30))
    files_per_step = max(1, int(getattr(cfg, "cluster_refiner_files_per_step", 2)))
    delta_reg = float(getattr(cfg, "cluster_refiner_delta_reg", 0.01))
    best_state = None
    best_val_f1 = -1.0

    for epoch in range(epochs):
        model.train()
        rng = np.random.default_rng(int(cfg.split_seed) + 40111 * (epoch + 1))
        order = np.arange(len(train_items), dtype=np.int64)
        rng.shuffle(order)
        losses = []
        regs = []
        for start in range(0, len(order), files_per_step):
            batch_idx = order[start:start + files_per_step]
            opt.zero_grad(set_to_none=True)
            file_losses = []
            file_regs = []
            for ii in batch_idx:
                item = train_items[int(ii)]
                if len(item["y"]) == 0:
                    continue
                x = torch.from_numpy(item["x"].astype(np.float32)).to(device)
                y = torch.from_numpy(item["y"].astype(np.float32)).to(device)
                base_logit = torch.from_numpy(item["base_logit"].astype(np.float32)).to(device)
                delta = model(x)
                refined_logit = base_logit + delta
                file_losses.append(crit(refined_logit, y))
                file_regs.append(torch.mean(delta * delta))
            if not file_losses:
                continue
            bce = torch.stack(file_losses).mean()
            reg = torch.stack(file_regs).mean() if file_regs else torch.tensor(0.0, device=device)
            loss = bce + delta_reg * reg
            loss.backward()
            opt.step()
            losses.append(float(bce.detach().cpu()))
            regs.append(float(reg.detach().cpu()))

        predict_cluster_aware_pt_refiner_records(model, val_records, feat_mean, feat_std, cfg, out_key="cluster_refiner_prob", quiet=True)
        val_prob = np.concatenate([r["cluster_refiner_prob"] for r in val_records if len(r.get("cluster_refiner_prob", []))], axis=0) if val_records else np.zeros(0, dtype=np.float32)
        val_y = np.concatenate([r["downsampled"]["label"] for r in val_records if len(r["downsampled"]["label"])], axis=0) if val_records else np.zeros(0, dtype=np.int64)
        val_f1 = binary_metrics(val_y, val_prob >= 0.5)["f1"] if len(val_y) else 0.0
        if val_f1 > best_val_f1:
            best_val_f1 = val_f1
            best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
        print(
            f"[ClusterAwarePT] epoch={epoch+1:03d}/{epochs} "
            f"loss={float(np.mean(losses)) if losses else 0.0:.5f} "
            f"delta_reg={float(np.mean(regs)) if regs else 0.0:.5f} "
            f"val_f1@0.5={val_f1:.4f} "
            f"thr={getattr(cfg, 'cluster_refiner_high_threshold', 0.70):.2f} eps={getattr(cfg, 'cluster_refiner_eps_mm', 3.0):.2f}"
        )

    if best_state is not None:
        model.load_state_dict(best_state)
    model._cluster_refiner_in_dim = in_dim
    return model


def predict_cluster_aware_pt_refiner_records(model: nn.Module, records: List[Dict[str, object]], feat_mean: np.ndarray, feat_std: np.ndarray, cfg: Config, out_key: str = "cluster_refiner_prob", quiet: bool = False) -> pd.DataFrame:
    base_key = str(getattr(cfg, "cluster_refiner_base_prob_key", "token_transformer_prob"))
    device = torch.device(cfg.device)
    model.eval()
    iterator = records if quiet else tqdm(records, desc="Predict cluster-aware PT refiner")
    cluster_rows = []
    with torch.no_grad():
        for r in iterator:
            n = len(r["downsampled"]["label"])
            if n == 0:
                r[out_key] = np.zeros(0, dtype=np.float32)
                continue
            x_np, comp_df = compute_cluster_aware_token_features(r, feat_mean, feat_std, cfg, prob_key=base_key)
            if comp_df is not None and not comp_df.empty and not quiet:
                cluster_rows.append(comp_df)
            base_prob = np.asarray(r.get(base_key, np.zeros(n, dtype=np.float32)), dtype=np.float32)
            if len(base_prob) != n:
                base_prob = np.zeros(n, dtype=np.float32)
            base_logit = torch.from_numpy(_safe_prob_to_logit(base_prob).astype(np.float32)).to(device)
            x = torch.from_numpy(x_np.astype(np.float32)).to(device)
            delta = model(x)
            refined_logit = base_logit + delta
            r[out_key] = torch.sigmoid(refined_logit).detach().cpu().numpy().astype(np.float32)
    if cluster_rows:
        return pd.concat(cluster_rows, axis=0, ignore_index=True)
    return pd.DataFrame()


